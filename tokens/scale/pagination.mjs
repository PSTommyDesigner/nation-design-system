//    ทั้งที่กดไม่ได้ ซึ่งหลอกผู้ใช้ และโปรแกรมอ่านหน้าจอก็อ่านว่าเป็นปุ่ม
// ─────────────────────────────────────────────────────────────
import { SIZES, RADIUS_FORMULA, CONTROL_HEIGHT } from './global-scale.config.mjs';

export const name = 'pagination';

export const PAGINATION_SIZES = SIZES;

export const USAGE = {
  xs: 'ในแผงแคบหรือในการ์ดเล็กที่พื้นที่แนวตั้งจำกัด',
  sm: 'ใต้ตารางในหลังบ้านที่มีของเยอะบนจอ',
  md: 'ค่าเริ่มต้นของระบบ ใช้กับหน้ารายการข่าวและหลังบ้านทั่วไป',
  lg: 'หน้ารายการที่เป็นเนื้อหาหลักของหน้า',
  xl: 'จอใหญ่ระยะไกล',
};

// ชุดตัวอักษรของเลขหน้าและข้อความก่อนหน้าถัดไป
// ของเดิมใช้ 14 ทุกขนาดเพราะไม่มีแกนขนาด ชุดใหม่เดินตามขั้น
export const LABEL_PRESET = {
  xs: { name: 'label/xs', size: 10 },
  sm: { name: 'label/sm', size: 12 },
  md: { name: 'label/md', size: 14 },
  lg: { name: 'label/lg', size: 16 },
  xl: { name: 'label/xl', size: 18 },
};

// ── ของกลาง ยืมมาทั้งก้อน ────────────────────────────────────
export const HEIGHT = CONTROL_HEIGHT;          // 24 · 32 · 40 · 48 · 56 (md คง 40 ตามค่าเดิม)
export const RADIUS = RADIUS_FORMULA.pagination; // 6 · 7 · 8 · 9 · 10 (md คง 8 ตามค่าเดิม)

// ── semantic knobs เฉพาะของหน้านี้ ───────────────────────────
export const GAP = { base: 2, step: 1 };        // 2 · 3 · 4 · 5 · 6  ช่องไฟระหว่างปุ่มเลขที่ติดกัน
export const GROUP_GAP = { base: 12, step: 4 }; // 12 · 16 · 20 · 24 · 28 (md คง 20 ตามค่าเดิม)
// ระยะขอบซ้ายขวาของปุ่มเลข เผื่อไว้ให้เลขสามหลักขึ้นไปไม่ชนขอบ
// ปุ่มเป็นจัตุรัสเมื่อเลขหลักเดียว แล้วกว้างขึ้นเองเมื่อเลขยาวขึ้น
export const PADDING_X = { base: 4, step: 2 };  // 4 · 6 · 8 · 10 · 12

// ── ค่าอนุพันธ์ ห้ามตั้งเอง ───────────────────────────────────
const at = (s) => SIZES.indexOf(s);
const height = (s) => HEIGHT.base + at(s) * HEIGHT.step;
const radius = (s) => RADIUS.base + at(s) * RADIUS.step;
const gap = (s) => GAP.base + at(s) * GAP.step;
const groupGap = (s) => GROUP_GAP.base + at(s) * GROUP_GAP.step;
const paddingX = (s) => PADDING_X.base + at(s) * PADDING_X.step;
// ปุ่มเลขเป็นจัตุรัสเป็นอย่างน้อย ความกว้างขั้นต่ำจึงเท่ากับความสูงเสมอ
const minWidth = (s) => height(s);

// ── build ────────────────────────────────────────────────────
export function build(dim) {
  // ด่านตรวจของกลาง ถ้าหลุดจากกันเมื่อไหร่ ปุ่มเลขหน้าจะไม่เท่าปุ่มอื่นในระบบ
  if (HEIGHT.base !== CONTROL_HEIGHT.base || HEIGHT.step !== CONTROL_HEIGHT.step) {
    throw new Error(
      `pagination: ความสูงปุ่ม (base ${HEIGHT.base} step ${HEIGHT.step}) ` +
      `ไม่ตรงกับความสูงกลางของระบบ (base ${CONTROL_HEIGHT.base} step ${CONTROL_HEIGHT.step}) ` +
      `ปุ่มเลขหน้าเป็นปุ่มเหมือนกัน ต้องสูงเท่ากับปุ่มอื่นเสมอ`
    );
  }
  if (RADIUS.base !== RADIUS_FORMULA.button.base || RADIUS.step !== RADIUS_FORMULA.button.step) {
    throw new Error(
      `pagination: มุมโค้ง (base ${RADIUS.base} step ${RADIUS.step}) ` +
      `ไม่ตรงกับสูตรมุมโค้งปุ่มของระบบ (base ${RADIUS_FORMULA.button.base} step ${RADIUS_FORMULA.button.step}) ` +
      `มุมโค้งเป็นบุคลิกของแบรนด์ ปุ่มทุกชนิดต้องใช้ค่าเดียวกัน`
    );
  }
  for (const s of PAGINATION_SIZES) {
    if (minWidth(s) !== height(s)) {
      throw new Error(`pagination: ขนาด ${s} ปุ่มเลขไม่เป็นจัตุรัส (กว้างขั้นต่ำ ${minWidth(s)} สูง ${height(s)})`);
    }
    if (paddingX(s) * 2 >= minWidth(s)) {
      throw new Error(`pagination: ขนาด ${s} ระยะขอบซ้ายขวารวมกัน ${paddingX(s) * 2} กินพื้นที่เกินความกว้างขั้นต่ำ ${minWidth(s)} เลขจะไม่มีที่อยู่`);
    }
    if (gap(s) >= groupGap(s)) {
      throw new Error(`pagination: ขนาด ${s} ช่องไฟระหว่างเลข ${gap(s)} ไม่น้อยกว่าช่องไฟระหว่างกลุ่ม ${groupGap(s)} กลุ่มจะแยกกันไม่ออก`);
    }
  }

  const grow = (fn, note) =>
    Object.fromEntries(PAGINATION_SIZES.map((s) => [s, { ...dim(fn(s)), $description: note(fn(s), s) }]));

  const component = {
    height: grow(height, (v, s) =>
      `ความสูงปุ่มในแถบแบ่งหน้าขนาด ${s} เท่ากับ ${v}px อ่านจากความสูงกลางของระบบ ใช้ทั้งปุ่มเลขหน้าและปุ่มก่อนหน้าถัดไป ของเดิมสองตัวนี้สูงไม่เท่ากัน คือ 40 กับ 38`),
    'min-width': grow(minWidth, (v, s) =>
      `ความกว้างขั้นต่ำของปุ่มเลขหน้าขนาด ${s} เท่ากับ ${v}px เท่ากับความสูงเสมอ ปุ่มจึงเป็นจัตุรัสเมื่อเลขหลักเดียว แล้วกว้างขึ้นเองเมื่อเลขยาวขึ้น ห้ามพิมพ์มือ`),
    'padding-x': grow(paddingX, (v, s) =>
      `ระยะขอบซ้ายขวาของปุ่มเลขหน้าขนาด ${s} เท่ากับ ${v}px เผื่อไว้ให้เลขสามหลักขึ้นไปไม่ชนขอบ ไม่มีระยะขอบแนวตั้งโดยตั้งใจ เพราะความสูงปุ่มเป็นตัวคุมแล้ว`),
    gap: grow(gap, (v, s) =>
      `ช่องไฟระหว่างปุ่มเลขหน้าที่อยู่ติดกันของขนาด ${s} เท่ากับ ${v}px แคบกว่าช่องไฟระหว่างกลุ่มเสมอ เพื่อให้เห็นว่าเลขทั้งแถวเป็นกลุ่มเดียวกัน`),
    'group-gap': grow(groupGap, (v, s) =>
      `ช่องไฟระหว่างกลุ่มของขนาด ${s} เท่ากับ ${v}px คือระยะระหว่างปุ่มก่อนหน้า กลุ่มเลข และปุ่มถัดไป ขนาด md เท่ากับ 20 ตรงกับค่าที่วัดได้จากไฟล์ออกแบบเดิม`),
  };

  const semantic = {
    gap: { base: dim(GAP.base), step: dim(GAP.step) },
    'group-gap': { base: dim(GROUP_GAP.base), step: dim(GROUP_GAP.step) },
    'padding-x': { base: dim(PADDING_X.base), step: dim(PADDING_X.step) },
    // ความสูงกับมุมโค้งไม่มี base หรือ step ของตัวเอง เพราะยืมของกลางมาทั้งก้อน
  };

  const radiusOut = Object.fromEntries(
    PAGINATION_SIZES.map((s) => [s, {
      ...dim(radius(s)),
      $description: `มุมโค้งปุ่มเลขหน้าขนาด ${s} เท่ากับ ${radius(s)}px อ่านจากสูตรมุมโค้งปุ่มของระบบ ทรงวงกลมใช้ค่าเต็มแทน ซึ่งเป็นคุณสมบัติของชิ้นงาน ไม่ใช่ตัวแปร`,
    }])
  );

  const checks = [
    {
      label: 'ความกว้างขั้นต่ำของปุ่มเลข ต้องเท่ากับความสูงปุ่ม',
      eq: (a, s) => [a('min-width', s), a('height', s)],
    },
  ];

  return { name, semantic, component, radius: radiusOut, radiusAppliesTo: ['pagination'], checks };
}
