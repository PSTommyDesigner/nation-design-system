//    เพราะเฟรมเป็นขนาดตายตัว ค่าจึงค้างจากรุ่นเก่า ค่าจริงคือ (40 ลบ 22) หารสอง เท่ากับ 9
//    ชุดใหม่ไม่ตั้งระยะขอบแนวตั้งเลย ให้ความสูงปุ่มเป็นตัวคุม แล้ววางเนื้อหากึ่งกลาง
