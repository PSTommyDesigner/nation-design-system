// ทำตามแบบของ toggle.mjs กับ checkbox.mjs ทุกชั้น
// ค่าทุกตัวมาจากงานวิจัย docs/research/slider-component.md และคำตัดสินของผู้ใช้ 2026-09-24
//
// ── โครงสองชั้น (เหมือนช่องติ๊กและสวิตช์) ─────────────────────
//   ชั้นที่ 1 ภาพแถบเลื่อน  ราง กับ ปุ่มจับ มีสเกลของตัวเอง ไม่ผูก CONTROL_HEIGHT
//   ชั้นที่ 2 แถวที่กดได้   ผูก CONTROL_HEIGHT ตรง ๆ เป็นกล่องครอบที่ให้พื้นที่แตะ
//
//   เหตุผลสามข้อ (งานวิจัยหัวข้อ 12.3)
//     1. WCAG SC 2.5.8 นับแถบเลื่อนทั้งตัวเป็นเป้าเดียว ไม่ได้นับปุ่มจับแยก
//        และ SC 2.5.7 ต้องแตะที่รางได้ ความสูงที่มีผลจริงจึงเป็นแถว ไม่ใช่ปุ่มจับ
//     2. Spectrum เป็นเจ้าเดียวที่มีหลายขนาดแล้วผูกกับสเกลกลาง ทำแบบนี้ทุกประการ
//     3. ได้แถวสูงเท่าปุ่มและช่องกรอก จึงวางแถบเลื่อนคู่ช่องกรอกตัวเลขในแถวเดียวกันได้พอดี
//        ซึ่งเป็นรูปแบบที่ตลาดแนะนำ (Carbon ทำเป็นค่าเริ่มต้น)
//
// ⚠️ ห้ามเขียนขนาดปุ่มจับหรือรางเป็นสูตรอนุพันธ์ของ CONTROL_HEIGHT เด็ดขาด
//    บทเรียนเดียวกับที่ toggle.mjs checkbox.mjs และ avatar.mjs เขียนกำกับไว้
//    ช่องว่างระหว่างแถวกับปุ่มจับไม่คงที่ (4 · 6 · 8 · 10 · 12) เพราะสองสเกลใช้ step ต่างกัน
//
// ⚠️ แต่ ROW_HEIGHT ต้องอ้าง CONTROL_HEIGHT จริง ๆ ห้ามพิมพ์ค่าซ้ำ
//    ถ้าวันหนึ่งความสูงปุ่มขยับ แถวของแถบเลื่อนต้องขยับตาม
//
// ── สิ่งที่เปลี่ยนจากของเดิมในไฟล์ออกแบบ ─────────────────────
//   1. จาก 1 ขนาด เป็น 5 ขนาด (ผู้ใช้ตัดสิน 2026-09-24 ให้เท่ากับสวิตช์ ช่องติ๊ก และปุ่ม)
//      ขนาด md คงค่าเดิมทุกค่า คือ ปุ่มจับ 24 ราง 8 ของเดิมจึงไม่ขยับ
//   2. ความยาวเลิกตายตัวที่ 320 เปลี่ยนเป็นยืดตามกรอบแม่
//      ค่าเดิมมาจาก Untitled UI kit ที่ออกแบบให้มีขนาดเดียว ขัดกับการใช้งานจริง
//      ที่แถบเลื่อนส่วนใหญ่ยืดเต็มความกว้าง (Carbon กำหนดช่วง 200 ถึง 640)
//   3. เพิ่มสถานะกดกับปิดใช้งาน ของเดิมมีแค่ ปกติ ชี้ และโฟกัส
//
// ⚠️ ไม่มี token ความยาว โดยตั้งใจ
//    ความยาวมาจากกรอบแม่ ไม่ใช่ค่าของ component ถ้าตั้งเป็น token จะมีคนเอาไปตรึงความกว้าง
//    ซึ่งเป็นปัญหาเดิมของไฟล์นี้ (ตายตัว 320 ทุกที่)
//
// ⚠️ ไม่มี token สีหรือความหนาของแถบเติม
//    แถบเติมใช้รางตัวเดียวกันแล้วเปลี่ยนสี ความหนาจึงเท่ากันเสมอ
// ─────────────────────────────────────────────────────────────
import { SIZES, RADIUS_SCALE, CONTROL_HEIGHT } from './global-scale.config.mjs';

export const name = 'slider';

// ── ขนาดที่แถบเลื่อนเปิดใช้ (ครบทุกขั้นเท่าสวิตช์และปุ่ม) ─────
export const SLIDER_SIZES = SIZES;

// ── semantic knobs · ชั้นภาพ ──────────────────────────────────
// base คิดที่ดัชนี xs → md = base + 2×step
//
// ปุ่มจับ 16 · 20 · 24 · 28 · 32
//   md คง 24 ตามค่าเดิมในไฟล์ · xs ที่ 16 ตรงกับค่าที่ตลาดใช้มากที่สุด (ช่วง 16 ถึง 20)
//   xl ที่ 32 ยังเล็กกว่าปุ่มขนาด xl (56) เกือบครึ่ง จึงไม่ถือว่าเกิน
export const HANDLE = { base: 16, step: 4 };
// ราง 4 · 6 · 8 · 10 · 12
//   md คง 8 ตามค่าเดิม · xs ที่ 4 ตรงกับค่าที่ตลาดใช้มากที่สุด (ช่วง 2 ถึง 4)
export const TRACK = { base: 4, step: 2 };

// ── semantic knobs · ชั้นแถวที่กดได้ ──────────────────────────
export const ROW_HEIGHT = CONTROL_HEIGHT;  // 24 · 32 · 40 · 48 · 56 (อ้างสเกลกลาง ห้ามพิมพ์ค่าซ้ำ)
// บนอุปกรณ์สัมผัสใช้ค่าที่มากกว่าระหว่าง 48 (ค่าเดียวกับช่องติ๊กและปุ่มตัวเลือก) กับแถวปกติ
// จึงได้ 48 · 48 · 48 · 48 · 56 ไม่ใช่ค่าเดียวทุกขนาดแบบช่องติ๊ก เพราะ xl สูงกว่า 48 อยู่แล้ว
export const ROW_HEIGHT_TOUCH_MIN = 48;

// ทั้งรางและปุ่มจับเป็นทรงแคปซูลกับวงกลม จึงใช้มุมโค้งเต็มค่าเดียว ไม่ผันตามขนาด
export const RADIUS_FULL = RADIUS_SCALE.full;

// ── build: คืน semantic (knob) + component (resolved sizes) ───
export function build(dim) {
  const at = (s) => SIZES.indexOf(s);

  const handle = (s) => HANDLE.base + at(s) * HANDLE.step;
  const track = (s) => TRACK.base + at(s) * TRACK.step;
  const rowH = (s) => ROW_HEIGHT.base + at(s) * ROW_HEIGHT.step;
  const rowTouch = (s) => Math.max(ROW_HEIGHT_TOUCH_MIN, rowH(s));
  // ผลลัพธ์ล้วน ห้ามตั้งแยก
  const inset = (s) => (rowH(s) - handle(s)) / 2;      // ช่องบนล่างระหว่างแถวกับปุ่มจับ
  const overhang = (s) => (handle(s) - track(s)) / 2;  // ปุ่มจับยื่นพ้นรางข้างละ

  // ── ด่านตรวจ ต้องสอดคล้องกันเองทุกขนาด ─────────────────────
  for (const s of SLIDER_SIZES) {
    if (rowH(s) < handle(s)) {
      throw new Error(`slider: ขนาด ${s} แถวเตี้ยกว่าปุ่มจับ (${rowH(s)} < ${handle(s)})`);
    }
    if (handle(s) <= track(s)) {
      throw new Error(`slider: ขนาด ${s} ปุ่มจับไม่ใหญ่กว่าราง (${handle(s)} ≤ ${track(s)}) ปุ่มจับจะจมหายในราง`);
    }
    if ((rowH(s) - handle(s)) % 2 !== 0) {
      throw new Error(`slider: ขนาด ${s} ช่องบนล่างไม่ลงตัว (${rowH(s)} ลบ ${handle(s)} หารสองไม่ลงตัว) ปุ่มจับจะไม่อยู่กึ่งกลางแถวพอดี`);
    }
    if ((handle(s) - track(s)) % 2 !== 0) {
      throw new Error(`slider: ขนาด ${s} ส่วนยื่นไม่ลงตัว (${handle(s)} ลบ ${track(s)} หารสองไม่ลงตัว) ปุ่มจับจะไม่อยู่กึ่งกลางรางพอดี`);
    }
  }

  const grow = (fn, note) =>
    Object.fromEntries(SLIDER_SIZES.map((s) => [s, { ...dim(fn(s)), $description: note(fn(s), s) }]));

  const component = {
    handle: grow(handle, (v, s) =>
      `เส้นผ่านศูนย์กลางปุ่มจับของแถบเลื่อนขนาด ${s} เท่ากับ ${v}px เป็นค่าตั้งต้นของ component เลือกอิสระ ไม่ได้ผูกกับความสูงปุ่ม`),
    track: grow(track, (v, s) =>
      `ความหนารางของแถบเลื่อนขนาด ${s} เท่ากับ ${v}px แถบเติมใช้รางตัวเดียวกันจึงหนาเท่ากันเสมอ`),
    overhang: grow(overhang, (v, s) =>
      `ปุ่มจับยื่นพ้นรางข้างละ ${v}px ในขนาด ${s} มาจาก (ปุ่มจับ ${handle(s)} ลบ ราง ${track(s)}) หารสอง ห้ามพิมพ์มือ`),
    inset: grow(inset, (v, s) =>
      `ช่องบนล่างระหว่างแถวกับปุ่มจับของขนาด ${s} เท่ากับ ${v}px มาจาก (แถว ${rowH(s)} ลบ ปุ่มจับ ${handle(s)}) หารสอง ห้ามพิมพ์มือ`),
    row: {
      height: grow(rowH, (v, s) =>
        `ความสูงแถวที่กดได้ของแถบเลื่อนขนาด ${s} เท่ากับ ${v}px อ้างสเกลความสูงตัวควบคุมกลาง ทำให้วางแถวเดียวกับปุ่มและช่องกรอกได้พอดี ปุ่มจับ ${handle(s)}px จัดกึ่งกลาง เหลือช่องบนล่างข้างละ ${inset(s)}px`),
      'height-touch': grow(rowTouch, (v, s) =>
        `ความสูงแถวบนอุปกรณ์สัมผัสของขนาด ${s} เท่ากับ ${v}px ใช้ค่าที่มากกว่าระหว่าง ${ROW_HEIGHT_TOUCH_MIN} กับแถวปกติ ${rowH(s)} ผ่านทั้งเกณฑ์ 48dp ของ Android และ 44pt ของ Apple`),
      // พื้นที่แตะของปุ่มจับแต่ละอันเป็นสี่เหลี่ยมจัตุรัสเท่าความสูงแถว
      // สำคัญกับแบบช่วงที่ปุ่มจับสองอันอาจเลื่อนมาชิดกัน
      'handle-target': grow(rowH, (v, s) =>
        `พื้นที่แตะของปุ่มจับแต่ละอันในขนาด ${s} เป็นสี่เหลี่ยมจัตุรัส ${v}px เท่าความสูงแถว ใช้กับแบบช่วงที่ปุ่มจับอาจเลื่อนมาชิดกัน`),
    },
  };

  const semantic = {
    handle: { base: dim(HANDLE.base), step: dim(HANDLE.step) },
    track: { base: dim(TRACK.base), step: dim(TRACK.step) },
    // แถวอ้างสเกลกลาง ค่าที่เห็นตรงนี้จึงเท่ากับ CONTROL_HEIGHT เสมอ ไม่ได้พิมพ์ซ้ำ
    row: { base: dim(ROW_HEIGHT.base), step: dim(ROW_HEIGHT.step), 'touch-min': dim(ROW_HEIGHT_TOUCH_MIN) },
  };

  // มุมโค้งเต็มค่าเดียว ไม่ผันตามขนาด (ทำแบบเดียวกับ toggle/radius/full)
  const radius = {
    full: {
      ...dim(RADIUS_FULL),
      $description: 'มุมโค้งเต็มของรางและปุ่มจับ ใช้ค่าเดียวทุกขนาด เพราะรางเป็นแคปซูลและปุ่มจับเป็นวงกลมเสมอ ไม่ผันตามขนาดแบบช่องกรอกหรือปุ่ม',
    },
  };

  // สมการปิด ให้ด่านตรวจ spacing บวกกลับทุกขนาดตอน build
  const checks = [
    {
      label: 'แถว ต้องเท่ากับ ปุ่มจับ บวก ช่องบนล่างสองข้าง',
      eq: (a, s) => [a('row.height', s), a('handle', s) + a('inset', s) * 2],
    },
    {
      label: 'ปุ่มจับ ต้องเท่ากับ ราง บวก ส่วนยื่นสองข้าง',
      eq: (a, s) => [a('handle', s), a('track', s) + a('overhang', s) * 2],
    },
  ];

  return { name, semantic, component, radius, radiusAppliesTo: ['slider'], checks };
}
