// ─────────────────────────────────────────────────────────────
// TAB component (แท็บ · หน้า 18 Tabs)
//
// ครอบคลุม 4 ชุดบนหน้า 18 ที่ใช้ตัวเลขชุดเดียวกันทั้งหมด
//   segmented-tab        ชิ้นเดี่ยวทรงกล่องติดกันเป็นแถบ มีแกน current
//   underline-tab        ชิ้นเดี่ยวทรงขีดเส้นใต้ มีแกน current
//   segmented-tab-group  กล่องครอบของทรงกล่อง มีมุมโค้งและเงา
//   underline-tab-group  กล่องครอบของทรงขีดเส้นใต้ ไม่มีมุมโค้ง
//
// ค่าทุกตัวมาจากการวัดไฟล์ออกแบบจริง 2026-09-29 (363 node) บวกงานวิจัย
// docs/research/tabs-component.md และคำตัดสินของผู้ใช้วันเดียวกัน
//
// ── ทำไมความสูงอ้าง CONTROL_HEIGHT ───────────────────────────
//   แท็บคือตัวควบคุมที่วางในแถวเดียวกับปุ่มและช่องกรอกจริง เช่นแถบกรองข่าว
//   ที่มีแท็บหมวดอยู่ซ้ายและปุ่มเรียงลำดับอยู่ขวา ถ้าความสูงหลุดจากกันแม้ 2px จะเห็นทันที
//   เหตุผลเต็มอยู่ที่หัวคอมเมนต์ของ CONTROL_HEIGHT ใน global-scale.config.mjs
//
//   ของเดิมในไฟล์ออกแบบมีปัญหานี้อยู่แล้ว ทรงกล่องสูง 40 (ตรงขั้น md พอดี)
//   แต่ทรงขีดเส้นใต้สูง 38 ซึ่งไม่ตรงขั้นไหนเลยในสเกลกลาง
//   สาเหตุคือสองทรงใช้ text style คนละตัว (ทรงกล่องเป็นค่าดิบ Prompt Regular 14 สูง 24
//   ส่วนทรงขีดเส้นใต้ใช้ preset ที่ความสูงบรรทัด 22) งานนี้จึงบังคับให้ทั้งสองทรง
//   ใช้ preset ตระกูลเดียวกันและสูงเท่ากันทุกขนาด
//
// ⚠️ ระยะขอบบนล่างเป็นค่าอนุพันธ์ ห้ามตั้งเอง
//    padding.y = (ความสูง ลบ ความสูงบรรทัดของ preset) หารสอง
//    ได้ 4, 5, 8, 11, 14 ซึ่ง "ไม่เป็นสูตร base+step" โดยตั้งใจ
//    เพราะความสูงบรรทัดของ label/* เองไม่ได้เรียงเป็นขั้นเท่ากัน (16, 22, 24, 26, 28)
//    เป็นกรณีเดียวกับระยะขอบของแท็กและป้ายที่มีคอมเมนต์ห้ามยัดเป็นสูตรไว้แล้ว
//
// ⚠️ ขนาด xs ตัวอักษรเล็กมาก ผู้ใช้ตัดสินแล้วว่าเปิดใช้ (2026-09-29)
//    xs สูง 24 ทำให้เลือก preset ได้ตัวเดียวคือ label/xs ที่ 10px
//    เพราะ label/sm มีความสูงบรรทัด 22 ซึ่งจะเหลือระยะขอบข้างละ 1 เท่านั้น
//    งานวิจัยพบว่าไม่มี DS เจ้าไหนใน 15 เจ้าลงไปต่ำกว่า 12px และไม่มีเจ้าไหนทำถึง 5 ขนาด
//    ผู้ใช้รับทราบแล้วและเลือกเปิดครบ 5 ขนาดให้เหมือนหน้าอื่นในระบบ
//    ข้อนี้ต้องเขียนกำกับในเอกสารว่า xs ใช้เฉพาะแผงตั้งค่าที่หนาแน่นบนเดสก์ท็อป ห้ามใช้บนมือถือ
//
// ⚠️ พื้นที่แตะไม่ผ่านเกณฑ์ 44 แม้ขนาด md (งานวิจัยหัวข้อพื้นที่แตะ)
//    แท็บต่างจากแถบเลื่อนตรงที่ยืดความสูงไม่ได้ ยืดลงไปทับแผงเนื้อหา ยืดขึ้นไปทับหัวข้อ
//    จึงไม่ทำ ROW_HEIGHT แบบแถบเลื่อน แต่ให้ฝั่งโค้ดซ้อนชั้นมองไม่เห็นที่ min-height 44
//    เฉพาะ pointer แบบหยาบ (วิธีของ Primer) ไม่มี token ของเรื่องนี้ เพราะเป็นค่าคงที่ของมาตรฐาน
//
// ⚠️ ความหนาตัวชี้คงที่ทุกขนาด ไม่ผันตามขนาด (ผู้ใช้ตัดสิน 2026-10-01)
//    งานวิจัยพบว่าไม่มีเจ้าไหนให้ความหนาตัวชี้โตตามขนาด ทุกเจ้าคงที่ และค่าที่ใช้มากที่สุดคือ 2
//    ของเดิมในไฟล์ออกแบบเป็น 1 ซึ่งบางเกินไปจนแท็บปัจจุบันไม่เด่นพอ
//
// ⚠️ ตัวชี้กับเส้นรางแยก token กัน ห้ามรวมเป็นตัวเดียว
//    ตัวชี้คือขีดใต้แท็บปัจจุบัน เส้นรางคือเส้นที่แท็บอื่นวางอยู่ ต่อกันเป็นเส้นเดียวทั้งแถว
//    ถ้าใช้ค่าเดียวกัน พอทำตัวชี้หนาขึ้นเป็น 2 เส้นรางจะหนาตามไปด้วย ซึ่งไม่ใช่สิ่งที่ตั้งใจ
//    ตลาดใช้ราง 1 คู่กับตัวชี้ 2 เป็นค่าปกติ
//
// ⚠️ ไม่มี token ความกว้าง โดยตั้งใจ
//    ความกว้างแท็บมาจากเนื้อหา (hug) และความกว้างกลุ่มมาจากกรอบแม่
//    ถ้าตั้งเป็น token จะมีคนเอาไปตรึงความกว้างแล้วข้อความยาวจะล้น
// ─────────────────────────────────────────────────────────────
import { SIZES, RADIUS_FORMULA, CONTROL_HEIGHT } from './global-scale.config.mjs';

export const name = 'tab';

// ── ขนาดที่แท็บเปิดใช้ (ครบทุกขั้น ผู้ใช้ตัดสิน 2026-09-29) ────
export const TAB_SIZES = SIZES;

// ── semantic knobs ───────────────────────────────────────────
// ความสูงอ้างสเกลกลางตรง ๆ ห้ามพิมพ์ค่าซ้ำ ถ้าความสูงปุ่มขยับ แท็บต้องขยับตาม
export const HEIGHT = CONTROL_HEIGHT; // 24 · 32 · 40 · 48 · 56

// text style ที่แต่ละขนาดใช้ กับความสูงบรรทัดของมัน (ตัวกำหนดระยะขอบบนล่าง)
// ใช้ตระกูล label เพราะกฎบทบาทฟอนต์ใน CLAUDE.md กำหนดว่า Prompt คือ functional/UI
// และ label คือ preset ของป้ายกำกับในชิ้นงาน ตรงกับหน้าที่ของข้อความในแท็บ
export const TEXT_PRESET = {
  xs: { name: 'label/xs', line: 16 },
  sm: { name: 'label/sm', line: 22 },
  md: { name: 'label/md', line: 24 },
  lg: { name: 'label/lg', line: 26 },
  xl: { name: 'label/xl', line: 28 },
};

export const PADDING_X = { base: 8, step: 4 }; // 8 · 12 · 16 · 20 · 24 (md คง 16 ตามค่าเดิมในไฟล์)
export const GAP = { base: 4, step: 2 };       // 4 · 6 · 8 · 10 · 12  (md คง 8 ตามค่าเดิม)
export const ICON = { base: 16, step: 2 };     // 16 · 18 · 20 · 22 · 24 (ชุดเดียวกับปุ่มและปุ่มลิงก์)
export const UNREAD = { base: 6, step: 1 };    // 6 · 7 · 8 · 9 · 10   (md คง 8 ตามค่าเดิม)

export const INDICATOR = 2; // ขีดใต้แท็บปัจจุบัน
export const RAIL = 1;      // เส้นรางที่แท็บอื่นวางอยู่ ของทรงขีดเส้นใต้
export const DIVIDER = 1;   // เส้นแบ่งระหว่างแท็บ ของทรงกล่อง

// มุมโค้งของกล่องครอบทรงกล่อง โตตามขนาด 4 5 6 7 8 (ผู้ใช้ตัดสิน 2026-10-02)
// สูตรอยู่ที่ RADIUS_FORMULA.tab ในสเกลกลาง เพราะมุมโค้งเป็นบุคลิกของแบรนด์
export const RADIUS_GROUP = RADIUS_FORMULA.tab;

// ── ค่าอนุพันธ์ ห้ามตั้งเอง ───────────────────────────────────
const at = (s) => SIZES.indexOf(s);
const height = (s) => HEIGHT.base + at(s) * HEIGHT.step;
const paddingX = (s) => PADDING_X.base + at(s) * PADDING_X.step;
const gap = (s) => GAP.base + at(s) * GAP.step;
const icon = (s) => ICON.base + at(s) * ICON.step;
const unread = (s) => UNREAD.base + at(s) * UNREAD.step;
// ระยะขอบบนล่างของแท็บที่มีข้อความ
const paddingY = (s) => (height(s) - TEXT_PRESET[s].line) / 2;
// ระยะขอบของแท็บแบบไอคอนอย่างเดียว ทุกด้านเท่ากัน
const paddingIconOnly = (s) => (height(s) - icon(s)) / 2;

// ── build ────────────────────────────────────────────────────
export function build(dim) {
  // ด่านตรวจ ต้องสอดคล้องกันเองทุกขนาด ก่อนปล่อยค่าออกไป
  for (const s of TAB_SIZES) {
    const line = TEXT_PRESET[s].line;
    if (height(s) < line) {
      throw new Error(`tab: ขนาด ${s} กล่องเตี้ยกว่าความสูงบรรทัด (${height(s)} < ${line}) ข้อความจะล้นออกนอกกล่อง`);
    }
    if ((height(s) - line) % 2 !== 0) {
      throw new Error(`tab: ขนาด ${s} ระยะขอบบนล่างไม่ลงตัว (${height(s)} ลบ ${line} หารสองไม่ลงตัว) ข้อความจะไม่อยู่กึ่งกลางกล่องพอดี`);
    }
    if (height(s) < icon(s)) {
      throw new Error(`tab: ขนาด ${s} กล่องเตี้ยกว่าไอคอน (${height(s)} < ${icon(s)})`);
    }
    if ((height(s) - icon(s)) % 2 !== 0) {
      throw new Error(`tab: ขนาด ${s} ระยะขอบของแบบไอคอนอย่างเดียวไม่ลงตัว (${height(s)} ลบ ${icon(s)} หารสองไม่ลงตัว)`);
    }
    if (unread(s) >= icon(s)) {
      throw new Error(`tab: ขนาด ${s} จุดแจ้งเตือนไม่เล็กกว่าไอคอน (${unread(s)} ≥ ${icon(s)}) จะดูเป็นไอคอนกลมแทนที่จะเป็นจุด`);
    }
  }

  const grow = (fn, note) =>
    Object.fromEntries(TAB_SIZES.map((s) => [s, { ...dim(fn(s)), $description: note(fn(s), s) }]));

  const component = {
    height: grow(height, (v, s) =>
      `ความสูงแท็บขนาด ${s} เท่ากับ ${v}px อ้างสเกลความสูงตัวควบคุมกลาง ทำให้วางแถวเดียวกับปุ่มและช่องกรอกได้พอดี ใช้เท่ากันทั้งทรงกล่องและทรงขีดเส้นใต้ ของเดิมสองทรงสูง 40 กับ 38 ไม่เท่ากัน`),
    padding: {
      x: grow(paddingX, (v, s) =>
        `ระยะขอบซ้ายขวาของแท็บขนาด ${s} เท่ากับ ${v}px ใช้กับแท็บที่มีข้อความเท่านั้น แบบไอคอนอย่างเดียวใช้ padding.icon-only ซึ่งเท่ากันทุกด้าน`),
      y: grow(paddingY, (v, s) =>
        `ระยะขอบบนล่างของแท็บขนาด ${s} เท่ากับ ${v}px เป็นค่าอนุพันธ์ คิดจาก (ความสูง ${height(s)} ลบ ความสูงบรรทัดของ ${TEXT_PRESET[s].name} คือ ${TEXT_PRESET[s].line}) หารสอง ห้ามพิมพ์มือ ชุดนี้ไม่เป็นเส้นตรงเพราะความสูงบรรทัดของ preset ไม่ได้เรียงเป็นขั้นเท่ากัน`),
      'icon-only': grow(paddingIconOnly, (v, s) =>
        `ระยะขอบของแท็บแบบไอคอนอย่างเดียวขนาด ${s} เท่ากับ ${v}px เท่ากันทุกด้าน คิดจาก (ความสูง ${height(s)} ลบ ไอคอน ${icon(s)}) หารสอง บวกกลับต้องได้ ${height(s)} เสมอ ทำให้แบบไอคอนอย่างเดียวสูงเท่าแบบข้อความ ของเดิมสูง 36 ไม่เท่าเพื่อน`),
    },
    gap: grow(gap, (v, s) =>
      `ช่องไฟระหว่างไอคอนหรือจุดแจ้งเตือนกับข้อความของแท็บขนาด ${s} เท่ากับ ${v}px แบบไอคอนอย่างเดียวไม่ใช้ค่านี้เพราะมีลูกตัวเดียว`),
    icon: grow(icon, (v, s) =>
      `ขนาดไอคอนในแท็บขนาด ${s} เท่ากับ ${v}px ใช้ชุดเดียวกับปุ่มและปุ่มลิงก์ กรอบไอคอนล็อกสัดส่วน 1 ต่อ 1`),
    unread: grow(unread, (v, s) =>
      `เส้นผ่านศูนย์กลางจุดแจ้งเตือนในแท็บขนาด ${s} เท่ากับ ${v}px จุดนี้บอกว่ามีของใหม่ยังไม่ได้อ่าน ไม่ใช่สถานะของแท็บ จึงใช้ชื่อ unread ไม่ใช่ dot และห้ามสื่อความหมายด้วยสีอย่างเดียวตาม WCAG 1.4.1`),
    indicator: {
      ...dim(INDICATOR),
      $description: `ความหนาขีดใต้แท็บปัจจุบันของทรงขีดเส้นใต้ เท่ากับ ${INDICATOR}px คงที่ทุกขนาด ไม่ผันตามขนาด ห้ามใช้ค่านี้กับเส้นรางของแท็บอื่น เส้นรางมี tab/rail ของตัวเอง`,
    },
    rail: {
      ...dim(RAIL),
      $description: `ความหนาเส้นรางที่แท็บอื่นวางอยู่ เท่ากับ ${RAIL}px บางกว่าขีดใต้แท็บปัจจุบันที่ ${INDICATOR}px เพื่อให้แท็บปัจจุบันเด่นออกมาจากแถว คงที่ทุกขนาด`,
    },
    divider: {
      ...dim(DIVIDER),
      $description: `ความหนาเส้นแบ่งระหว่างแท็บของทรงกล่อง เท่ากับ ${DIVIDER}px คงที่ทุกขนาด แยก token จาก tab/rail เพราะคนละหน้าที่ ตัวหนึ่งคั่นแท็บ อีกตัวเป็นรางใต้แท็บ ค่าเท่ากันตอนนี้แต่ปรับแยกกันได้`,
    },
  };

  const semantic = {
    // ความสูงอ้างสเกลกลาง ค่าที่เห็นตรงนี้จึงเท่ากับ CONTROL_HEIGHT เสมอ ไม่ได้พิมพ์ซ้ำ
    height: { base: dim(HEIGHT.base), step: dim(HEIGHT.step) },
    padding: { base: dim(PADDING_X.base), step: dim(PADDING_X.step) },
    gap: { base: dim(GAP.base), step: dim(GAP.step) },
    icon: { base: dim(ICON.base), step: dim(ICON.step) },
    unread: { base: dim(UNREAD.base), step: dim(UNREAD.step) },
    // padding.y ไม่มี base/step โดยตั้งใจ เพราะตัวคุมคือความสูงบรรทัดของ preset ไม่ใช่ตัวเลขในไฟล์นี้
  };

  const groupRadius = (s) => RADIUS_GROUP.base + at(s) * RADIUS_GROUP.step;
  const radius = {
    group: Object.fromEntries(TAB_SIZES.map((s) => [s, {
      ...dim(groupRadius(s)),
      $description: `มุมโค้งของกล่องครอบทรงกล่องขนาด ${s} เท่ากับ ${groupRadius(s)}px โตตามขนาดด้วยสูตร base ${RADIUS_GROUP.base} step ${RADIUS_GROUP.step} ทรงขีดเส้นใต้ไม่มีมุมโค้งเพราะไม่มีกล่อง`,
    }])),
  };

  // สมการปิด ให้ด่านตรวจ spacing บวกกลับทุกขนาดตอน build
  const checks = [
    {
      label: 'ความสูง ต้องเท่ากับ ไอคอน บวก ระยะขอบแบบไอคอนอย่างเดียวสองข้าง',
      eq: (a, s) => [a('height', s), a('icon', s) + a('padding.icon-only', s) * 2],
    },
  ];

  return { name, semantic, component, radius, radiusAppliesTo: ['tab'], checks };
}
