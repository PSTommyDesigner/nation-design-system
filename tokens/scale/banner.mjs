// ⚠️ ปุ่มกระทำอยู่ใต้ข้อความเสมอ ไม่ใช่ท้ายแถวเดียวกัน
//    ของเดิมวางปุ่มไว้ท้ายแถว ซึ่งพอข้อความยาวหลายบรรทัดปุ่มจะลอยอยู่กลางอากาศ
//    4 เจ้าวางใต้ข้อความตลอดเวลา ส่วน Primer ทำกลไกย้ายอัตโนมัติที่จุดตัด 500
//    ผู้ใช้เลือกแบบวางใต้ตลอดเวลา เพราะไม่ต้องมีจุดตัดให้ดูแลเพิ่ม
// ─────────────────────────────────────────────────────────────
import { SIZES, RADIUS_SCALE, RADIUS_FORMULA } from './global-scale.config.mjs';

export const name = 'banner';

// ── ขนาดที่เปิดใช้ (ครบทุกขั้น ผู้ใช้ตัดสิน 2026-10-02) ────────
export const BANNER_SIZES = SIZES;

// แต่ละขั้นมีไว้ทำอะไร ใช้เขียนลงเอกสารและ $description
export const USAGE = {
  xs: 'แถบในแผงตั้งค่าหรือในการ์ดเล็ก ที่พื้นที่แนวตั้งมีจำกัด',
  sm: 'แถบในฟอร์มและในกล่องเนื้อหาที่มีของเยอะบนจอ',
  md: 'ค่าเริ่มต้นของระบบ ใช้กับเว็บข่าวทุกแบรนด์ ถ้าไม่รู้จะเลือกอะไรให้ใช้ตัวนี้',
  lg: 'แถบระดับหน้าที่ต้องเห็นชัดตั้งแต่เปิดเข้ามา',
  xl: 'จอใหญ่ระยะไกล หรือหน้าที่ตัวอักษรใหญ่กว่าปกติทั้งหน้า',
};

// ── text style ที่แต่ละขนาดใช้ ────────────────────────────────
// ชุดเดียวกับข้อความแจ้งลอยทุกขั้น เพื่อให้สองตัวนี้วางคู่กันแล้วตัวอักษรเท่ากัน
export const TITLE_PRESET = {
  xs: { name: 'label/sm', size: 12, line: 22 },
  sm: { name: 'label/md', size: 14, line: 24 },
  md: { name: 'label/lg', size: 16, line: 26 },
  lg: { name: 'label/xl', size: 18, line: 28 },
  xl: { name: 'title/lg', size: 20, line: 30 },
};

export const SUPPORT_PRESET = {
  xs: { name: 'body/xs', size: 12, line: 22 },
  sm: { name: 'body/xs', size: 12, line: 22 },
  md: { name: 'body/sm', size: 14, line: 24 },
  lg: { name: 'body/md', size: 16, line: 26 },
  xl: { name: 'body/lg', size: 18, line: 28 },
};

// ── semantic knobs ───────────────────────────────────────────
export const PADDING = { base: 8, step: 4 };  // 8 · 12 · 16 · 20 · 24 (md คง 16 ตามค่าเดิม)
export const GAP = { base: 8, step: 4 };      // 8 · 12 · 16 · 20 · 24 (md คง 16 ตามค่าเดิม)
export const ICON = { base: 20, step: 2 };    // 20 · 22 · 24 · 26 · 28 (md คง 24 ตามค่าเดิม)
export const STACK = { base: 0, step: 1 };    // 0 · 1 · 2 · 3 · 4  ระยะหัวข้อกับข้อความรอง

// ระยะจากกลุ่มข้อความลงมาถึงปุ่มกระทำ ใหญ่กว่า stack เพราะคนละระดับความสัมพันธ์
// stack คั่นสองบรรทัดของข้อความก้อนเดียวกัน ส่วนตัวนี้คั่นข้อความกับสิ่งที่กดได้
export const ACTION_GAP = { base: 4, step: 2 }; // 4 · 6 · 8 · 10 · 12

// มุมโค้งของระดับ section สูตรอยู่ที่ RADIUS_FORMULA.banner ในสเกลกลาง
export const RADIUS_SECTION = RADIUS_FORMULA.banner; // 8 · 12 · 16 · 20 · 24

// ── ค่าอนุพันธ์ ห้ามตั้งเอง ───────────────────────────────────
const at = (s) => SIZES.indexOf(s);
const padding = (s) => PADDING.base + at(s) * PADDING.step;
const gap = (s) => GAP.base + at(s) * GAP.step;
const icon = (s) => ICON.base + at(s) * ICON.step;
const stack = (s) => STACK.base + at(s) * STACK.step;
const actionGap = (s) => ACTION_GAP.base + at(s) * ACTION_GAP.step;
const radiusSection = (s) => RADIUS_SECTION.base + at(s) * RADIUS_SECTION.step;

// ── build ────────────────────────────────────────────────────
export function build(dim) {
  for (const s of BANNER_SIZES) {
    if (SUPPORT_PRESET[s].size > TITLE_PRESET[s].size) {
      throw new Error(`banner: ขนาด ${s} ข้อความรองตัวโตกว่าหัวข้อ (${SUPPORT_PRESET[s].size} > ${TITLE_PRESET[s].size}) ลำดับความสำคัญจะกลับหัว`);
    }
    if (icon(s) > TITLE_PRESET[s].line) {
      throw new Error(`banner: ขนาด ${s} ไอคอนสูงกว่าบรรทัดหัวข้อ (${icon(s)} > ${TITLE_PRESET[s].line}) ไอคอนจะไม่อยู่ในแนวเดียวกับบรรทัดแรก`);
    }
    if (actionGap(s) <= stack(s)) {
      throw new Error(`banner: ขนาด ${s} ระยะถึงปุ่มกระทำไม่มากกว่าระยะระหว่างสองบรรทัดข้อความ (${actionGap(s)} ไม่มากกว่า ${stack(s)}) ปุ่มจะดูเป็นบรรทัดที่สามของข้อความ`);
    }
  }

  const grow = (fn, note) =>
    Object.fromEntries(BANNER_SIZES.map((s) => [s, { ...dim(fn(s)), $description: note(fn(s), s) }]));

  const component = {
    padding: grow(padding, (v, s) =>
      `ระยะขอบแถบแจ้งในหน้าขนาด ${s} เท่ากับ ${v}px เท่ากันทั้งสี่ด้าน ใช้ค่าเดียวกับข้อความแจ้งลอยทุกขั้น เพื่อให้สองตัวนี้วางคู่กันแล้วขอบตรงกัน ขนาด md เท่ากับ 16 ตรงกับค่าที่วัดได้จากไฟล์ออกแบบเดิม`),
    gap: grow(gap, (v, s) =>
      `ช่องไฟระหว่างไอคอน กลุ่มข้อความ และปุ่มปิด ของขนาด ${s} เท่ากับ ${v}px ใช้ค่าเดียวกันทั้งสองช่อง เพื่อให้สามก้อนเรียงห่างเท่ากันทั้งแถว`),
    stack: grow(stack, (v, s) =>
      `ระยะระหว่างหัวข้อกับข้อความรองของขนาด ${s} เท่ากับ ${v}px ขนาด xs เป็น 0 เพราะความสูงบรรทัดของ ${TITLE_PRESET.xs.name} เผื่อระยะไว้พอแล้ว`),
    'action-gap': grow(actionGap, (v, s) =>
      `ระยะจากกลุ่มข้อความลงมาถึงปุ่มกระทำของขนาด ${s} เท่ากับ ${v}px มากกว่า stack ของขนาดเดียวกันเสมอ เพราะคนละระดับความสัมพันธ์ ถ้าเท่ากันปุ่มจะดูเป็นบรรทัดที่สามของข้อความ`),
    icon: grow(icon, (v, s) =>
      `ขนาดไอคอนบอกชนิดของขนาด ${s} เท่ากับ ${v}px ปุ่มปิดใช้ขนาดเดียวกัน ตรงกับของเดิมที่ทั้งสองตัวเป็น 24 เท่ากัน`),
  };

  const semantic = {
    padding: { base: dim(PADDING.base), step: dim(PADDING.step) },
    gap: { base: dim(GAP.base), step: dim(GAP.step) },
    icon: { base: dim(ICON.base), step: dim(ICON.step) },
    stack: { base: dim(STACK.base), step: dim(STACK.step) },
    'action-gap': { base: dim(ACTION_GAP.base), step: dim(ACTION_GAP.step) },
    // ไม่มีความกว้างและความสูง โดยตั้งใจ ทั้งสองมาจากกรอบแม่และจากเนื้อหา
  };

  const radiusOut = {
    page: {
      ...dim(RADIUS_SCALE.none),
      $description: `มุมโค้งของแถบระดับหน้า เท่ากับ ${RADIUS_SCALE.none}px ทุกขนาด เพราะแถบระดับนี้ยืนเต็มความกว้างจนชนขอบจอทั้งสองข้าง ถ้าใส่มุมโค้งจะเห็นสีพื้นหลังโผล่ที่มุมแล้วดูเหมือนวางผิดที่ วิธีแยกสองระดับด้วยมุมโค้งเป็นของ Fluent 2`,
    },
    section: Object.fromEntries(BANNER_SIZES.map((s) => [s, {
      ...dim(radiusSection(s)),
      $description: `มุมโค้งของแถบระดับกล่องเนื้อหาขนาด ${s} เท่ากับ ${radiusSection(s)}px โตตามขนาดด้วยสูตร base ${RADIUS_SECTION.base} step ${RADIUS_SECTION.step} ใช้ชุดเดียวกับข้อความแจ้งลอย ขนาด md เท่ากับ 16 ตรงกับค่าเดิมในไฟล์ออกแบบ`,
    }])),
  };

  return { name, semantic, component, radius: radiusOut, radiusAppliesTo: ['banner'] };
}
