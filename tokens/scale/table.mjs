//           avatar-group 12+40+12=64 · text 12+46+12=70
//    ถ้าวันหลังมีคนตั้งความสูงตายตัว ต้องกลับมาทำสูตรให้ ไม่ใช่ปล่อยเป็นตัวเลขลอย
