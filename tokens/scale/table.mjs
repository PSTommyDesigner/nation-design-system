//     ระยะภายในระหว่างลูก 8
//   ค่าสองตัวนี้บังเอิญตรงกับขั้น s2/xs และ s1/lg ของสเกลจัดหน้า แต่ไม่ได้อ้างถึงกัน
//   เพราะระยะห่างภายในชิ้นงานเป็นของชิ้นงานนั้นเอง (ขอบเขตที่ตัดสิน 2026-08-26)
//
// ⚠️ ไม่มีสูตรความสูงของเซล โดยตั้งใจ
//    เซลทุกตัวตั้ง primaryAxisSizingMode และ counterAxisSizingMode เป็น AUTO
//    ความสูงจึงมาจากเนื้อหาข้างใน ต่างกันตั้งแต่ 40 ถึง 70 ตามชนิดของลูก
//    ตรวจแล้วบวกกลับได้ครบทั้ง 15 ตัว ระยะขอบบน 12 บวก ความสูงลูก บวก ระยะขอบล่าง 12 เท่ากับความสูงเซลเป๊ะ
