import { RADIUS_SCALE } from './global-scale.config.mjs';

export const name = 'table';

export const RADIUS = RADIUS_SCALE.md; // 8px
export const CORNERS = ['top-left', 'top-right', 'bottom-right', 'bottom-left'];

// ── semantic knobs · ระยะห่างของเซล ───────────────────────────
export const CELL_PADDING = 12; // เท่ากันทั้งสี่ด้าน
export const CELL_GAP = 8;      // ระยะระหว่างลูกในเซล เช่น รูปกับข้อความ หรือข้อความกับไอคอนเรียง

export function build(dim) {
  const radius = Object.fromEntries(CORNERS.map((c) => [c, dim(RADIUS)]));

  // ค่าเดี่ยวทั้งหมด ไม่มีชุดขนาด เพราะเซลตารางมีขนาดเดียว
  // ทุกตัวต้องมี $description ตามด่านตรวจ spacing ใน scripts/generate-scale.mjs
  const pad = (side) => ({
    ...dim(CELL_PADDING),
    $description: `ระยะขอบ${side}ของเซลตาราง ${CELL_PADDING}px เท่ากันทั้งสี่ด้าน อ่านจากต้นฉบับทั้ง 15 ชนิดเมื่อ 2026-09-11`,
  });

  const component = {
    padding: {
      t: pad('บน'),
      r: pad('ขวา'),
      b: pad('ล่าง'),
      l: pad('ซ้าย'),
    },
    gap: {
      ...dim(CELL_GAP),
      $description: `ระยะระหว่างลูกในเซลตาราง ${CELL_GAP}px ใช้กับเซลที่มีลูกมากกว่าหนึ่งชิ้น เช่น user link-button หรือดาว`,
    },
  };

  // ไม่มี base และ step เพราะไม่มีชุดขนาด semantic tier จึงเก็บแค่ค่าที่ตัดสินไว้
  const semantic = {
    padding: dim(CELL_PADDING),
    gap: dim(CELL_GAP),
  };

  return { name, semantic, component, radius, radiusAppliesTo: ['table'] };
}
