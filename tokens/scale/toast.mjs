//    เขียนไว้ในเอกสารและในโค้ดแทน
//
// ⚠️ ไอคอนใหญ่กว่าชุดของปุ่มและแท็บโดยตั้งใจ
//    ไอคอนในปุ่มอยู่ติดกับป้ายกำกับในตัวควบคุม อ่านคู่กันอยู่แล้ว
//    ส่วนไอคอนในข้อความแจ้งลอยทำหน้าที่บอกชนิดตั้งแต่แวบแรกก่อนที่คนจะอ่านข้อความ
//    จึงใช้ชุดที่เริ่มต้นใหญ่กว่า คือ 20 ถึง 28 แทนที่จะเป็น 16 ถึง 24
//
// ⚠️ ไม่มีกรอบสีรองไอคอนแล้ว (เปลี่ยนจากของเดิม 2026-10-02)
//    ของเดิมมีกรอบ 48x48 พื้นสีอ่อนมุมโค้ง 8 รองไอคอนไว้ เพราะตัวกล่องเป็นพื้นขาวหรือพื้นทึบ
//    เมื่อผู้ใช้ตัดสินให้ทำทรงพื้นอ่อนอย่างเดียว ตัวกล่องจะเป็นสีอ่อนของตระกูลนั้นอยู่แล้ว
//    กรอบสีอ่อนซ้อนบนพื้นสีอ่อนจะแทบมองไม่เห็น จึงใช้ไอคอนเปล่า ตรงกับที่ตลาดทำ
// ─────────────────────────────────────────────────────────────
import { SIZES, RADIUS_FORMULA } from './global-scale.config.mjs';

export const name = 'toast';

// ── ขนาดที่เปิดใช้ (ครบทุกขั้น ผู้ใช้ตัดสิน 2026-10-02) ────────
export const TOAST_SIZES = SIZES;

// แต่ละขั้นมีไว้ทำอะไร ใช้เขียนลงเอกสารและ $description
export const USAGE = {
  xs: 'แผงตั้งค่าที่หนาแน่นบนเดสก์ท็อป ข้อความสั้นบรรทัดเดียว',
  sm: 'เครื่องมือภายในและหน้าจัดการเนื้อหาที่มีของเยอะบนจอ',
  md: 'ค่าเริ่มต้นของระบบ ใช้กับเว็บข่าวทุกแบรนด์ ถ้าไม่รู้จะเลือกอะไรให้ใช้ตัวนี้',
  lg: 'หน้าที่ตัวอักษรใหญ่กว่าปกติ หรือข้อความแจ้งที่ต้องอ่านง่ายเป็นพิเศษ',
  xl: 'จอใหญ่ระยะไกล เช่นจอในห้องข่าวที่คนดูจากที่นั่งของตัวเอง',
};

// ── text style ที่แต่ละขนาดใช้ กับความสูงบรรทัดของมัน ─────────
// หัวข้อใช้ตระกูล label และ title ซึ่งเป็นน้ำหนัก medium ตามกฎบทบาทฟอนต์ใน CLAUDE.md
// ที่กำหนดว่า Prompt คือ functional และ UI ส่วนข้อความรองใช้ตระกูล body น้ำหนัก regular
// ขนาด md ตรงกับของเดิมในไฟล์ออกแบบ คือหัวข้อ 16 และข้อความรอง 14
export const TITLE_PRESET = {
  xs: { name: 'label/sm', size: 12, line: 22 },
  sm: { name: 'label/md', size: 14, line: 24 },
  md: { name: 'label/lg', size: 16, line: 26 },
  lg: { name: 'label/xl', size: 18, line: 28 },
  xl: { name: 'title/lg', size: 20, line: 30 },
};

export const SUPPORT_PRESET = {
  xs: { name: 'body/xs', size: 12, line: 22 },
  sm: { name: 'body/xs', size: 12, line: 22 },
  md: { name: 'body/sm', size: 14, line: 24 },
  lg: { name: 'body/md', size: 16, line: 26 },
  xl: { name: 'body/lg', size: 18, line: 28 },
};

// ── semantic knobs ───────────────────────────────────────────
// ความกว้างบนเดสก์ท็อป md เท่ากับ 360 ซึ่งเป็นค่าที่ผู้ใช้ตัดสิน
// และอยู่กลางย่านที่ตลาดใช้กันคือ 288 ถึง 400
export const WIDTH = { base: 280, step: 40 };   // 280 · 320 · 360 · 400 · 440
export const PADDING = { base: 8, step: 4 };    // 8 · 12 · 16 · 20 · 24 (md คง 16 ตามค่าเดิม)
export const GAP = { base: 8, step: 4 };        // 8 · 12 · 16 · 20 · 24 (md คง 16 ตามค่าเดิม)
export const ICON = { base: 20, step: 2 };      // 20 · 22 · 24 · 26 · 28 (md คง 24 ตามค่าเดิม)

// ระยะระหว่างหัวข้อกับข้อความรอง ของเดิมเป็น 0 เพราะความสูงบรรทัดเผื่อไว้แล้ว
// ยกขึ้นเป็นชุดที่โตตามขนาด เพื่อให้ขนาดใหญ่ไม่ดูอัดกันจนสองบรรทัดกลืนเป็นก้อนเดียว
export const STACK = { base: 0, step: 1 };      // 0 · 1 · 2 · 3 · 4

// ระยะจากกลุ่มข้อความลงมาถึงปุ่มกระทำ ใช้ชุดเดียวกับแถบแจ้งในหน้า
// ปุ่มกระทำอยู่ใต้ข้อความ ไม่ใช่ท้ายแถวเดียวกัน เพราะกล่องกว้างแค่ 280 ถึง 440
// พอวางปุ่มในแถวเดียวกับไอคอนและปุ่มปิด ที่เหลือให้ข้อความจะแคบจนตัดบรรทัดเสียรูป
// (เห็นจากการทดลองวางจริง 2026-10-02 ขนาด md เหลือที่ให้ข้อความไม่ถึงครึ่ง)
export const ACTION_GAP = { base: 4, step: 2 }; // 4 · 6 · 8 · 10 · 12

// มุมโค้ง สูตรอยู่ที่ RADIUS_FORMULA.toast ในสเกลกลาง เพราะมุมโค้งเป็นบุคลิกของแบรนด์
export const RADIUS = RADIUS_FORMULA.toast;     // 8 · 12 · 16 · 20 · 24

// ── ค่าอนุพันธ์ ห้ามตั้งเอง ───────────────────────────────────
const at = (s) => SIZES.indexOf(s);
const width = (s) => WIDTH.base + at(s) * WIDTH.step;
const padding = (s) => PADDING.base + at(s) * PADDING.step;
const gap = (s) => GAP.base + at(s) * GAP.step;
const icon = (s) => ICON.base + at(s) * ICON.step;
const stack = (s) => STACK.base + at(s) * STACK.step;
const actionGap = (s) => ACTION_GAP.base + at(s) * ACTION_GAP.step;
const radius = (s) => RADIUS.base + at(s) * RADIUS.step;
// ความกว้างที่เหลือให้ข้อความ หลังหักระยะขอบสองข้าง ไอคอน ช่องไฟ และปุ่มปิด
// ปุ่มปิดใช้ขนาดเดียวกับไอคอนชนิด ตรงกับของเดิมที่ทั้งสองตัวเป็น 24 เท่ากัน
const textWidth = (s) => width(s) - padding(s) * 2 - icon(s) * 2 - gap(s) * 2;

// ── build ────────────────────────────────────────────────────
export function build(dim) {
  // ด่านตรวจ ต้องสอดคล้องกันเองทุกขนาด ก่อนปล่อยค่าออกไป
  for (const s of TOAST_SIZES) {
    if (textWidth(s) <= 0) {
      throw new Error(`toast: ขนาด ${s} ไม่เหลือที่ให้ข้อความ (กว้าง ${width(s)} หักระยะขอบ ไอคอน และปุ่มปิดแล้วเหลือ ${textWidth(s)})`);
    }
    if (textWidth(s) < TITLE_PRESET[s].size * 8) {
      throw new Error(`toast: ขนาด ${s} ที่ว่างสำหรับข้อความแคบเกินไป เหลือ ${textWidth(s)}px ซึ่งใส่หัวข้อขนาด ${TITLE_PRESET[s].size}px ได้ไม่ถึง 8 ตัวอักษร`);
    }
    if (SUPPORT_PRESET[s].size > TITLE_PRESET[s].size) {
      throw new Error(`toast: ขนาด ${s} ข้อความรองตัวโตกว่าหัวข้อ (${SUPPORT_PRESET[s].size} > ${TITLE_PRESET[s].size}) ลำดับความสำคัญจะกลับหัว`);
    }
    if (actionGap(s) <= stack(s)) {
      throw new Error(`toast: ขนาด ${s} ระยะถึงปุ่มกระทำไม่มากกว่าระยะระหว่างสองบรรทัดข้อความ (${actionGap(s)} ไม่มากกว่า ${stack(s)}) ปุ่มจะดูเป็นบรรทัดที่สามของข้อความ`);
    }
    if (icon(s) > TITLE_PRESET[s].line) {
      throw new Error(`toast: ขนาด ${s} ไอคอนสูงกว่าบรรทัดหัวข้อ (${icon(s)} > ${TITLE_PRESET[s].line}) ไอคอนจะไม่อยู่ในแนวเดียวกับบรรทัดแรก`);
    }
  }

  const grow = (fn, note) =>
    Object.fromEntries(TOAST_SIZES.map((s) => [s, { ...dim(fn(s)), $description: note(fn(s), s) }]));

  const component = {
    width: grow(width, (v, s) =>
      `ความกว้างข้อความแจ้งลอยขนาด ${s} บนเดสก์ท็อป เท่ากับ ${v}px บนมือถือไม่ใช้ค่านี้ ให้ยืดเต็มความกว้างจอแล้วเว้นขอบข้างละเท่ากับ padding ของขนาดเดียวกัน ขนาด md เท่ากับ 360 ซึ่งอยู่กลางย่านที่ตลาดใช้คือ 288 ถึง 400`),
    padding: grow(padding, (v, s) =>
      `ระยะขอบข้อความแจ้งลอยขนาด ${s} เท่ากับ ${v}px เท่ากันทั้งสี่ด้าน ขนาด md เท่ากับ 16 ตรงกับค่าที่วัดได้จากไฟล์ออกแบบเดิมทั้ง 10 แบบ`),
    gap: grow(gap, (v, s) =>
      `ช่องไฟระหว่างไอคอน กลุ่มข้อความ และปุ่มปิด ของขนาด ${s} เท่ากับ ${v}px ใช้ค่าเดียวกันทั้งสองช่องโดยตั้งใจ เพื่อให้สามก้อนเรียงห่างเท่ากันทั้งแถว`),
    stack: grow(stack, (v, s) =>
      `ระยะระหว่างหัวข้อกับข้อความรองของขนาด ${s} เท่ากับ ${v}px ขนาด xs เป็น 0 เพราะความสูงบรรทัดของ ${TITLE_PRESET.xs.name} เผื่อระยะไว้พอแล้ว ขนาดใหญ่ขึ้นจึงค่อยเพิ่มทีละ 1 กันไม่ให้สองบรรทัดกลืนเป็นก้อนเดียว`),
    'action-gap': grow(actionGap, (v, s) =>
      `ระยะจากกลุ่มข้อความลงมาถึงปุ่มกระทำของขนาด ${s} เท่ากับ ${v}px มากกว่า stack ของขนาดเดียวกันเสมอ เพราะคนละระดับความสัมพันธ์ ใช้ชุดเดียวกับแถบแจ้งในหน้า`),
    icon: grow(icon, (v, s) =>
      `ขนาดไอคอนบอกชนิดของขนาด ${s} เท่ากับ ${v}px ปุ่มปิดใช้ขนาดเดียวกัน ตรงกับของเดิมที่ทั้งสองตัวเป็น 24 เท่ากัน ชุดนี้เริ่มต้นใหญ่กว่าไอคอนของปุ่มและแท็บ เพราะต้องอ่านออกตั้งแต่แวบแรกก่อนที่คนจะอ่านข้อความ`),
    'text-width': grow(textWidth, (v, s) =>
      `ความกว้างที่เหลือให้กลุ่มข้อความของขนาด ${s} เท่ากับ ${v}px เป็นค่าอนุพันธ์ คิดจาก ความกว้าง ${width(s)} ลบ ระยะขอบสองข้าง ${padding(s) * 2} ลบ ไอคอนกับปุ่มปิด ${icon(s) * 2} ลบ ช่องไฟสองช่อง ${gap(s) * 2} ห้ามพิมพ์มือ`),
  };

  const semantic = {
    width: { base: dim(WIDTH.base), step: dim(WIDTH.step) },
    padding: { base: dim(PADDING.base), step: dim(PADDING.step) },
    gap: { base: dim(GAP.base), step: dim(GAP.step) },
    icon: { base: dim(ICON.base), step: dim(ICON.step) },
    stack: { base: dim(STACK.base), step: dim(STACK.step) },
    'action-gap': { base: dim(ACTION_GAP.base), step: dim(ACTION_GAP.step) },
    // ไม่มี base หรือ step ของความสูง โดยตั้งใจ ความสูงมาจากเนื้อหา ไม่ใช่ตัวเลขในไฟล์นี้
  };

  const radiusOut = Object.fromEntries(TOAST_SIZES.map((s) => [s, {
    ...dim(radius(s)),
    $description: `มุมโค้งข้อความแจ้งลอยขนาด ${s} เท่ากับ ${radius(s)}px โตตามขนาดด้วยสูตร base ${RADIUS.base} step ${RADIUS.step} ขนาด md เท่ากับ 16 ตรงกับค่าเดิมในไฟล์ออกแบบ`,
  }]));

  // สมการปิด ให้ด่านตรวจบวกกลับทุกขนาดตอน build
  const checks = [
    {
      label: 'ความกว้าง ต้องเท่ากับ ระยะขอบสองข้าง บวก ไอคอน บวก ช่องไฟสองช่อง บวก กลุ่มข้อความ บวก ปุ่มปิด',
      eq: (a, s) => [
        a('width', s),
        a('padding', s) * 2 + a('icon', s) * 2 + a('gap', s) * 2 + a('text-width', s),
      ],
    },
  ];

  return { name, semantic, component, radius: radiusOut, radiusAppliesTo: ['toast'], checks };
}
