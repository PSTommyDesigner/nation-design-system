//
// ── ทำไมไม่มีสูตรความสูงและความกว้าง ─────────────────────────
//   ความสูงมาจากเนื้อหา และความกว้างหดตามเนื้อหาแล้วชนเพดานที่ max-width
//   12 ใน 15 เจ้าใช้ max-width และ 0 เจ้าตั้งความกว้างตายตัว
//   ของเดิมตั้ง counterAxisSizingMode เป็น FIXED ที่ 320 ทำให้ข้อความสั้นก็ยังกินกล่องเต็ม
//
// ── ทำไมมีแกนขนาด 5 ขั้น ทั้งที่ตลาดไม่มีสักเจ้า ──────────────
//   งานวิจัยพบว่า 0 ใน 15 เจ้าทำแกนขนาดให้คำใบ้ สิ่งที่ทำหน้าที่แทนคือ
//   "มีข้อความรองหรือไม่" ซึ่งเป็น 2 สภาพ ไม่ใช่ 5 ขั้น
//   ผู้ใช้ตัดสิน 2026-10-06 ให้ทำ 5 ขั้นเหมือนหน้าอื่นในระบบ เพื่อให้ทุกชิ้นในไลบรารีมีแกนเดียวกัน
//
// ⚠️ ขนาด md ของตัวอักษรไม่ตรงกับของเดิมและไม่ตรงกับตลาด โดยจำเป็น
//    ของเดิมและตลาดใช้ 12 ซึ่งในระบบเราคือ label/sm จึงตรงกับขั้น sm ไม่ใช่ md
//    เหตุผลคือบันไดตัวอักษรของระบบมีขั้นต่ำกว่า 12 อยู่ขั้นเดียว (10)
//    ถ้าดัน md ให้เป็น 12 จะเหลือที่ให้ xs กับ sm แค่ขั้นเดียว ต้องใช้ซ้ำกัน
//    จึงเลือกให้บันไดเดินเต็ม 5 ขั้นแทน แล้วเขียนกำกับในเอกสารว่า
//    **ถ้าต้องการความหนาแน่นเท่าที่ตลาดใช้ ให้เลือก sm** ส่วน md เป็นค่าเริ่มต้นของระบบ
//
// ⚠️ ระยะขอบรวมเป็นชุดเดียว ไม่แยกตามว่ามีข้อความรองหรือไม่
//    ของเดิมแยก คือแบบมีหัวข้ออย่างเดียวใช้ 8 และแบบมีข้อความรองใช้ 12
//    (ลอกมาจาก Untitled UI ที่ใช้ 12/8 กับ 12/12) การแยกแบบนั้นทำให้กล่องสองแบบ
//    วางเรียงกันแล้วขอบไม่ตรง จึงรวมเป็นค่าเดียวต่อขนาด
//
// ⚠️ ไม่มี token ของเวลาหน่วง โดยตั้งใจ
//    เวลาเป็นพฤติกรรม ไม่ใช่ขนาด และระบบมี motion/duration อยู่แล้ว
//    ค่าที่ตัดสินคือ หน่วงก่อนโผล่ 300 หน่วงก่อนหาย 150 และช่วงผ่อนผัน 300
//    เขียนไว้ในเอกสารและในโค้ดแทน
//
// ⚠️ ลูกศรไม่ได้อยู่ในชุด แต่เป็น component เดี่ยวชื่อ tooltip-arrow
//    ถ้าทำลูกศรเป็นแกน จำนวนแบบจะคูณ 4 ถึง 12 ทันที
//    และในโค้ดกลไกพลิกจัดการตำแหน่งลูกศรให้เองอยู่แล้ว
//    token ขนาดลูกศรยังอยู่ในไฟล์นี้ เพราะมันต้องโตตามขนาดกล่อง
// ─────────────────────────────────────────────────────────────
import { SIZES, RADIUS_FORMULA } from './global-scale.config.mjs';

export const name = 'tooltip';

export const TOOLTIP_SIZES = SIZES;

// แต่ละขั้นมีไว้ทำอะไร ใช้เขียนลงเอกสารและ $description
export const USAGE = {
  xs: 'แถบเครื่องมือที่หนาแน่นมากในหลังบ้าน เช่นแถบจัดรูปแบบข้อความที่มีปุ่มไอคอนเรียงกันสิบกว่าปุ่ม',
  sm: 'ความหนาแน่นเท่าที่ตลาดใช้กัน เลือกตัวนี้เมื่ออยากให้เท่ากับ DS เจ้าอื่น',
  md: 'ค่าเริ่มต้นของระบบ ใช้กับหลังบ้านทั่วไปและหน้าข่าวบนเดสก์ท็อป',
  lg: 'หน้าที่ตัวอักษรใหญ่กว่าปกติ หรือคำใบ้ที่ต้องอ่านง่ายเป็นพิเศษ',
  xl: 'จอใหญ่ระยะไกล เช่นจอในห้องข่าวที่คนดูจากที่นั่งของตัวเอง',
};

// ── text style ที่แต่ละขนาดใช้ ────────────────────────────────
// หัวข้อกับข้อความรองตัวเท่ากันทุกขั้น แยกกันด้วยน้ำหนักอย่างเดียว
// ซึ่งเป็นสิ่งที่ของเดิมทำอยู่แล้ว (ทั้งคู่ขนาด 12 น้ำหนัก 600 กับ 400)
// ขั้น xs ใช้ meta/credit เป็นข้อความรอง เพราะเป็น preset น้ำหนักปกติตัวเดียวที่ขนาด 10
export const TITLE_PRESET = {
  xs: { name: 'label/xs', size: 10, line: 16 },
  sm: { name: 'label/sm', size: 12, line: 22 },
  md: { name: 'label/md', size: 14, line: 24 },
  lg: { name: 'label/lg', size: 16, line: 26 },
  xl: { name: 'label/xl', size: 18, line: 28 },
};

export const SUPPORT_PRESET = {
  xs: { name: 'meta/credit', size: 10, line: 16 },
  sm: { name: 'body/xs', size: 12, line: 22 },
  md: { name: 'body/sm', size: 14, line: 24 },
  lg: { name: 'body/md', size: 16, line: 26 },
  xl: { name: 'body/lg', size: 18, line: 28 },
};

// ── semantic knobs ───────────────────────────────────────────
export const PADDING = { base: 8, step: 2 };      // 8 · 10 · 12 · 14 · 16 (md คง 12 ตามค่าเดิม)
export const STACK = { base: 2, step: 1 };        // 2 · 3 · 4 · 5 · 6    (md คง 4 ตามค่าเดิม)
export const ARROW = { base: 8, step: 2 };        // 8 · 10 · 12 · 14 · 16 ความกว้างฐานลูกศร
export const OFFSET = { base: 4, step: 1 };       // 4 · 5 · 6 · 7 · 8    ระยะจากตัวกระตุ้นถึงกล่อง

// ความกว้างสูงสุด แยกตามอุปกรณ์ เพราะจอมือถือแคบกว่ามาก
// มัธยฐานตลาด 250 และ 2 เจ้าที่สนใจเรื่องนี้ต่างก็มีค่าแยกตามอุปกรณ์
// คือ Spectrum (160 กับ 200) และ SLDS (320 กับ 160)
export const MAX_WIDTH_DESKTOP = { base: 200, step: 40 }; // 200 · 240 · 280 · 320 · 360
export const MAX_WIDTH_MOBILE = { base: 160, step: 40 };  // 160 · 200 · 240 · 280 · 320

export const RADIUS = RADIUS_FORMULA.tooltip;     // 4 · 6 · 8 · 10 · 12

// ── ค่าอนุพันธ์ ห้ามตั้งเอง ───────────────────────────────────
const at = (s) => SIZES.indexOf(s);
const padding = (s) => PADDING.base + at(s) * PADDING.step;
const stack = (s) => STACK.base + at(s) * STACK.step;
const arrowW = (s) => ARROW.base + at(s) * ARROW.step;
const offset = (s) => OFFSET.base + at(s) * OFFSET.step;
const maxDesktop = (s) => MAX_WIDTH_DESKTOP.base + at(s) * MAX_WIDTH_DESKTOP.step;
const maxMobile = (s) => MAX_WIDTH_MOBILE.base + at(s) * MAX_WIDTH_MOBILE.step;
const radius = (s) => RADIUS.base + at(s) * RADIUS.step;
// ความสูงลูกศรเป็นครึ่งหนึ่งของฐานเสมอ อัตราส่วน 2 ต่อ 1 ตรงกับ Carbon Ant Material และ Spectrum
const arrowH = (s) => arrowW(s) / 2;
// ความกว้างสูงสุดที่เหลือให้ตัวข้อความ หลังหักระยะขอบสองข้าง
// ต้องมีเป็น token ของตัวเอง เพราะในไฟล์ออกแบบ max-width ของกล่องไม่ได้บังคับให้ข้อความตัดบรรทัด
// ต้องไปตั้งที่ตัวข้อความเองด้วย (พบตอนประกอบจริง 2026-10-06 ข้อความรองล้นออกนอกกล่อง)
const textMax = (s) => maxDesktop(s) - padding(s) * 2;

// ── build ────────────────────────────────────────────────────
export function build(dim) {
  for (const s of TOOLTIP_SIZES) {
    if (SUPPORT_PRESET[s].size !== TITLE_PRESET[s].size) {
      throw new Error(`tooltip: ขนาด ${s} หัวข้อกับข้อความรองตัวไม่เท่ากัน (${TITLE_PRESET[s].size} กับ ${SUPPORT_PRESET[s].size}) ชุดนี้ตั้งใจให้ต่างกันแค่น้ำหนัก`);
    }
    if (!Number.isInteger(arrowH(s))) {
      throw new Error(`tooltip: ขนาด ${s} ความสูงลูกศรไม่ลงตัว (${arrowW(s)} หารสองไม่ลงตัว) ฐานลูกศรต้องเป็นเลขคู่`);
    }
    if (maxMobile(s) >= maxDesktop(s)) {
      throw new Error(`tooltip: ขนาด ${s} ความกว้างสูงสุดบนมือถือไม่น้อยกว่าบนเดสก์ท็อป (${maxMobile(s)} กับ ${maxDesktop(s)})`);
    }
    if (maxMobile(s) <= padding(s) * 2 + arrowW(s)) {
      throw new Error(`tooltip: ขนาด ${s} ความกว้างสูงสุดบนมือถือแคบกว่าระยะขอบสองข้างบวกฐานลูกศร ไม่เหลือที่ให้ข้อความ`);
    }
    if (arrowW(s) < radius(s)) {
      throw new Error(`tooltip: ขนาด ${s} ฐานลูกศรแคบกว่ามุมโค้ง (${arrowW(s)} < ${radius(s)}) ลูกศรจะถูกมุมโค้งกินจนดูไม่ออก`);
    }
  }

  const grow = (fn, note) =>
    Object.fromEntries(TOOLTIP_SIZES.map((s) => [s, { ...dim(fn(s)), $description: note(fn(s), s) }]));

  const component = {
    padding: grow(padding, (v, s) =>
      `ระยะขอบคำใบ้ขนาด ${s} เท่ากับ ${v}px เท่ากันทั้งสี่ด้าน และเท่ากันไม่ว่าจะมีข้อความรองหรือไม่ ขนาด md เท่ากับ 12 ตรงกับค่าที่วัดได้จากไฟล์ออกแบบเดิม ของเดิมแยกเป็น 8 กับ 12 ตามว่ามีข้อความรองไหม ซึ่งทำให้กล่องสองแบบวางเรียงกันแล้วขอบไม่ตรง`),
    stack: grow(stack, (v, s) =>
      `ระยะระหว่างหัวข้อกับข้อความรองของคำใบ้ขนาด ${s} เท่ากับ ${v}px ขนาด md เท่ากับ 4 ตรงกับค่าเดิม ใช้เฉพาะแบบที่เปิดข้อความรอง`),
    arrow: grow(arrowW, (v, s) =>
      `ความกว้างฐานลูกศรของคำใบ้ขนาด ${s} เท่ากับ ${v}px ความสูงเป็นครึ่งหนึ่งเสมอ ของเดิมคือ 8 คูณ 4 ซึ่งเป็นค่าต่ำสุดในตลาด ขยายเป็น 12 คูณ 6 ที่ขนาด md ตามค่าเริ่มต้นของ Carbon เพราะลูกศรสูง 4 บนกล่องมุมโค้ง 8 แทบมองไม่เห็น`),
    'arrow-height': grow(arrowH, (v, s) =>
      `ความสูงลูกศรของคำใบ้ขนาด ${s} เท่ากับ ${v}px เป็นค่าอนุพันธ์ คิดจากฐานลูกศร ${arrowW(s)} หารสอง อัตราส่วน 2 ต่อ 1 ตรงกับ Carbon Ant Material และ Spectrum ห้ามพิมพ์มือ`),
    offset: grow(offset, (v, s) =>
      `ระยะจากตัวกระตุ้นถึงขอบกล่องของคำใบ้ขนาด ${s} เท่ากับ ${v}px นับจากขอบกล่อง ไม่รวมลูกศร ขนาด md เท่ากับ 6 ซึ่งเป็นมัธยฐานของตลาด ของเดิมอ่านค่านี้ไม่ได้เพราะลูกศรฝังอยู่ในเฟรมที่ติดกับกล่อง`),
    'max-width': grow(maxDesktop, (v, s) =>
      `ความกว้างสูงสุดของคำใบ้ขนาด ${s} บนเดสก์ท็อป เท่ากับ ${v}px กล่องหดตามเนื้อหาแล้วชนเพดานนี้ ห้ามตั้งความกว้างตายตัว ขนาด md เท่ากับ 280 ซึ่งอยู่ในช่วงที่ตลาดทำกันมากที่สุดคือ 200 ถึง 320`),
    'text-max-width': grow(textMax, (v, s) =>
      `ความกว้างสูงสุดที่เหลือให้ตัวข้อความของคำใบ้ขนาด ${s} เท่ากับ ${v}px เป็นค่าอนุพันธ์ คิดจากความกว้างสูงสุด ${maxDesktop(s)} ลบระยะขอบสองข้าง ${padding(s) * 2} ห้ามพิมพ์มือ ต้องตั้งค่านี้ที่ตัวข้อความด้วย ไม่ใช่ตั้งแค่ที่กล่อง ไม่อย่างนั้นข้อความจะล้นออกนอกกล่อง`),
    'max-width-mobile': grow(maxMobile, (v, s) =>
      `ความกว้างสูงสุดของคำใบ้ขนาด ${s} บนมือถือ เท่ากับ ${v}px แคบกว่าบนเดสก์ท็อป 40 ทุกขั้น เพราะจอมือถือแคบกว่ามาก 2 เจ้าที่สนใจเรื่องนี้ต่างก็แยกค่าตามอุปกรณ์เหมือนกัน`),
  };

  const semantic = {
    padding: { base: dim(PADDING.base), step: dim(PADDING.step) },
    stack: { base: dim(STACK.base), step: dim(STACK.step) },
    arrow: { base: dim(ARROW.base), step: dim(ARROW.step) },
    offset: { base: dim(OFFSET.base), step: dim(OFFSET.step) },
    'max-width': { base: dim(MAX_WIDTH_DESKTOP.base), step: dim(MAX_WIDTH_DESKTOP.step) },
    'max-width-mobile': { base: dim(MAX_WIDTH_MOBILE.base), step: dim(MAX_WIDTH_MOBILE.step) },
    // ไม่มีความสูงและความกว้างจริง โดยตั้งใจ ทั้งคู่มาจากเนื้อหา
  };

  const radiusOut = Object.fromEntries(TOOLTIP_SIZES.map((s) => [s, {
    ...dim(radius(s)),
    $description: `มุมโค้งคำใบ้ขนาด ${s} เท่ากับ ${radius(s)}px โตตามขนาดด้วยสูตร base ${RADIUS.base} step ${RADIUS.step} ขนาด md เท่ากับ 8 ตรงกับค่าเดิมในไฟล์ออกแบบ และขั้น xs ที่ 4 ตรงกับมัธยฐานของตลาดพอดี`,
  }]));

  const checks = [
    {
      label: 'ความสูงลูกศร ต้องเท่ากับ ฐานลูกศร หารสอง',
      eq: (a, s) => [a('arrow-height', s) * 2, a('arrow', s)],
    },
    {
      label: 'ความกว้างสูงสุดบนมือถือ ต้องเท่ากับ บนเดสก์ท็อป ลบ 40',
      eq: (a, s) => [a('max-width-mobile', s) + 40, a('max-width', s)],
    },
    {
      label: 'ความกว้างข้อความ บวก ระยะขอบสองข้าง ต้องเท่ากับ ความกว้างสูงสุด',
      eq: (a, s) => [a('text-max-width', s) + a('padding', s) * 2, a('max-width', s)],
    },
  ];

  return { name, semantic, component, radius: radiusOut, radiusAppliesTo: ['tooltip'], checks };
}
