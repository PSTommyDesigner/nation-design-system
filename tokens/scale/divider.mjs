// ⚠️ อย่าสับสนกับ tab/divider (ผู้ใช้ทัก 2026-10-14)
//   tab/divider คือเส้นคั่น "ระหว่างแท็บ" ซึ่งเป็นขอบที่อยู่ข้างในชิ้นงานแท็บ ปรับพร้อมแท็บ
//   ส่วนไฟล์นี้คือเส้นที่ "วางเองระหว่าง section" เป็นชิ้นงานของตัวเอง หยิบไปวางที่ไหนก็ได้
//   ค่าเท่ากันที่ 1 โดยบังเอิญ แต่คนละหน้าที่ จึงต้องแยก token
//
//   ระบบนี้มีแบบแผนนี้อยู่แล้ว ดูที่ tabs.mjs ซึ่งแยก DIVIDER ออกจาก RAIL
//   ทั้งที่ทั้งคู่เป็น 1 โดยเขียนเหตุผลกำกับไว้ว่า "คนละหน้าที่ ค่าเท่ากันตอนนี้แต่ปรับแยกกันได้"
//
// ── ทำไมไม่มีสูตร base กับ step ─────────────────────────────
//   เส้นคั่นไม่มีหลายขนาด ความหนาจึงเป็นค่าคงที่ ไม่ต้องมีสูตร
//   ความยาวไม่ทำเป็น token เพราะเส้นยืดเต็มกรอบแม่เสมอ ความยาวจึงเป็นค่าของ layout
//
// ── ระยะประไม่ได้อยู่ในนี้ ───────────────────────────────────
//   เส้นประใช้ 8 เว้น 8 แต่ Figma ผูกตัวแปรกับระยะประไม่ได้
//   ถ้าใส่เป็น token ฝั่งโค้ดอย่างเดียว จะทำให้ตัวตรวจความตรงกันขึ้นเตือนตลอด
//   จึงเขียนค่าไว้ในเอกสารแทน ดู docs/28-dividers.md หัวข้อ 4.3
// ─────────────────────────────────────────────────────────────
import { DIVIDER as TAB_DIVIDER } from './tabs.mjs';

export const name = 'divider';

export const THICKNESS = 1;

export function build(dim) {
  if (!Number.isInteger(THICKNESS) || THICKNESS < 1) {
    throw new Error(`divider: ความหนาต้องเป็นจำนวนเต็มอย่างน้อย 1 (ได้ ${THICKNESS})`);
  }
  // ด่านเตือน ไม่ใช่ด่านบังคับ สองค่านี้ "ควร" ต่างกันได้ ถ้าวันหนึ่งต่างกันจริงให้ลบด่านนี้ทิ้ง
  // ที่ใส่ไว้เพราะถ้าใครแก้ค่าใดค่าหนึ่งแล้วอีกค่าไม่ขยับ จะได้รู้ตัวว่ากำลังทำให้สองเส้นหน้าตาไม่เหมือนกัน
  if (THICKNESS !== TAB_DIVIDER) {
    console.warn(
      `⚠️  divider: ความหนาเส้นคั่น section (${THICKNESS}) ไม่เท่ากับเส้นคั่นระหว่างแท็บ (${TAB_DIVIDER}) ` +
      `ซึ่งทำได้ เพราะคนละหน้าที่ แต่ถ้าไม่ได้ตั้งใจให้ต่าง ให้ไล่ดูว่าแก้ครบทั้งสองที่หรือยัง`
    );
  }

  const component = {
    thickness: {
      ...dim(THICKNESS),
      $description:
        `ความหนาเส้นคั่นระหว่างกลุ่มเนื้อหา เท่ากับ ${THICKNESS}px คงที่ เพราะเส้นคั่นไม่มีหลายขนาด ` +
        `แยก token จาก tab/divider เพราะคนละหน้าที่ ตัวนั้นคั่นระหว่างแท็บและอยู่ข้างในชิ้นงานแท็บ ` +
        `ตัวนี้วางเองระหว่าง section ค่าเท่ากันโดยบังเอิญ ปรับแยกกันได้`,
    },
  };

  return { name, semantic: null, component, radius: null, radiusAppliesTo: [] };
}
