// ค่าทุกตัววัดจากไฟล์ออกแบบจริง 2026-09-03 แล้วปรับตามผลวิจัย DS 12 เจ้า
// (docs/research/toggle-component.md) ตามที่ผู้ใช้ตัดสิน 2026-09-03
//
// ── โครงสองชั้น (แบบ Adobe Spectrum) ─────────────────────────
//   ชั้นที่ 1 ภาพสวิตช์   มีสเกลของตัวเอง ไม่ผูก CONTROL_HEIGHT
//   ชั้นที่ 2 แถวที่กดได้  ผูก CONTROL_HEIGHT ตรง ๆ เป็นกล่องครอบที่ให้พื้นที่แตะ
//
//   ชั้นที่สองแก้ 3 ปัญหาพร้อมกันด้วยกลไกเดียว
//     พื้นที่แตะผ่านเกณฑ์โดยไม่ต้องทำให้สวิตช์ที่ตาเห็นอ้วนขึ้น
//     สวิตช์วางเรียงแถวเดียวกับปุ่มและช่องกรอกได้พอดีเพราะแถวสูงเท่ากัน
//     ข้อความในสวิตช์พร้อมข้อความได้ที่ยึดสำหรับจัดวาง แทนการพิมพ์ระยะเยื้องมือ
//
// ── ทำไมชั้นภาพไม่ผูก CONTROL_HEIGHT ─────────────────────────
//   ไม่มีเจ้าไหนใน 12 เจ้าที่เอาตัวสวิตช์ไปผูกกับสเกลความสูงของปุ่ม
//   หลักฐานที่ชี้ขาดคือ IBM Carbon ซึ่งผูกความสูงปุ่มกับช่องกรอกด้วย mixin ตัวเดียวกัน
//   แต่ _toggle.scss ไม่ import utilities/layout เลย คือจงใจไม่ลากสวิตช์เข้าสเกลกลาง
//   เราใช้ Carbon เป็นเหตุผลหลักตอนตัดสินให้ช่องกรอกรวมสูตรกับปุ่ม (ดู input.mjs)
//   จึงต้องยอมรับ Carbon ตอนไม่ผูกสวิตช์ด้วย
//
//   เหตุผลเชิงการวางเลย์เอาต์ตรงกับกรณีอวาตาร์ ไม่ใช่กรณีช่องกรอก
//   สวิตช์ไม่ได้วางในแถวเดียวกับปุ่มแบบที่ช่องค้นหาวางคู่ปุ่มค้นหา
//   แต่วางในบรรทัดเดียวกับข้อความในรายการตั้งค่า
//   Ant Design ยืนยันเจตนานี้ด้วยโค้ด โดยตั้งความสูงรางเท่ากับหนึ่งบรรทัดข้อความพอดี
//
// ⚠️ ห้ามเขียนความสูงรางเป็นสูตรอนุพันธ์ของ CONTROL_HEIGHT เด็ดขาด
//    ตอนที่เปิดแค่ sm กับ md ระยะห่างบังเอิญเท่ากันที่ 12 ทั้งคู่ (20 ต่อ 32 และ 24 ต่อ 40)
//    ซึ่งชวนให้คิดว่าผูกกันได้ แต่พอเปิดครบ 5 ขนาดแล้วระยะห่างไม่คงที่เลย
//    คือ 8, 12, 16, 20, 24 เพราะสองสเกลใช้ step ต่างกัน (4 กับ 8)
//    นี่คือหลักฐานตรง ๆ ว่าสองชั้นนี้ไม่ได้มีความสัมพันธ์กันจริง
//    TRACK_HEIGHT มี base กับ step ของตัวเอง ถ้าจะแก้ให้แก้ที่ไฟล์นี้ ห้ามไปอ้าง button.mjs
//    (บทเรียนเดียวกับที่ avatar.mjs เขียนกำกับไว้)
//
// ⚠️ แต่ ROW_HEIGHT ต้องอ้าง CONTROL_HEIGHT จริง ๆ ห้ามพิมพ์ 32 กับ 40 ซ้ำ
//    นั่นคือจุดประสงค์ทั้งหมดของชั้นที่สอง ถ้าวันหนึ่งความสูงปุ่มขยับ แถวสวิตช์ต้องขยับตาม
//    ถ้าพิมพ์ค่าตายจะเกิดอาการเดียวกับ GitHub Primer คือฝั่งหนึ่งอ้าง token
//    ฝั่งหนึ่งพิมพ์ค่าตาย แล้วหลุดจากกันโดยไม่มีใครรู้
//
// ── สิ่งที่เปลี่ยนจากของเดิมในไฟล์ออกแบบ ─────────────────────
//   1. ความกว้างราง 36 → 40 และ 44 → 48 ให้ได้สัดส่วน 2.00 คงที่ทั้งสองขนาด
//      ของเดิมเป็น 1.80 กับ 1.83 ซึ่งเป็นอาการของการพิมพ์ความกว้างมือทีละขนาด
//      ค่าใหม่ตรงกับตลาดเป๊ะ 40x20 = Fluent 2 และ Atlassian · 48x24 = Carbon และ SLDS
//   2. มุมโค้ง 12 และระยะขอบใน 2 เคยเป็นค่าดิบไม่ผูกตัวแปร ตอนนี้เป็น token แล้ว
//   3. ระยะเยื้องของคำอธิบายมาจากสูตร ของเดิมพิมพ์มือแล้วขนาด sm ผิดไป 2px
//      (พิมพ์ 46 ค่าที่ถูกคือ 44) ซึ่งเป็นอาการเดียวกับที่เจอในช่องกรอก
//
// ⚠️ ห้ามให้ปุ่มกลมขยายหรือยืดตอนกดเด็ดขาด (ตัดสิน 2026-09-04 ผู้ใช้สั่ง)
//    ห้ามเพิ่ม token ความกว้างปุ่มกลมตอนกดกลับเข้ามาไม่ว่ากรณีใด
//    เคยเตรียมสูตร knob + inset x 2 ไว้เมื่อ 2026-09-03 แล้วถอดออก และตัดสินถาวรแล้วว่าไม่เอา
//    งานวิจัยที่ docs/research/toggle-component.md เสนอให้เปลี่ยนรูปทรงปุ่มกลมตอนกด
//    (Material 3 ขยายปุ่มกลม Ant ยืดปุ่มกลม 30 เปอร์เซ็นต์) แต่เราไม่ทำตามข้อนี้
//    สถานะกดของสวิตช์บอกด้วยสีอย่างเดียว ใช้ตัวแปรสีชุด pressed ที่สร้างไว้ทั้งระบบเมื่อ 2026-09-04
//    เหตุผลที่ต้องเขียนกำกับ เพราะงานวิจัยยังเสนออีกทาง ถ้าไม่จดไว้คนรุ่นหลังจะกลับไปทำตามงานวิจัย
//
// ── ทำไมเลือกสัดส่วน 2.00 ไม่ใช่กลุ่ม 1.6 ────────────────────
//   กลุ่ม 1.6 (Material 3 · Base Web รุ่นใหม่) ใช้ปุ่มกลมที่โตขึ้นตอนเปิดเป็นตัวชดเชย
//   เพราะสัดส่วนแคบทำให้ระยะเลื่อนสั้น สองอย่างนี้ต้องมาคู่กัน
//   ⚠️ ผลที่ตามมา ปุ่มกลมของเราโตตอนเปิดไม่ได้ เพราะเต็มรางอยู่แล้ว (เหลือช่องข้างละ 2)
//      กลไกบอกสถานะจึงใช้การขยับตำแหน่งปุ่มกลมอย่างเดียว ซึ่งผ่าน WCAG SC 1.4.1 อยู่แล้ว
//      เพราะไม่ได้สื่อด้วยสีอย่างเดียว (ตัดสิน 2026-09-03 ไม่ทำกลไกเพิ่ม)
//   เหตุผลเชิงตัวเลข 2.00 เป็นสัดส่วนเดียวที่ให้จำนวนเต็มทั้งสองขนาดจากความสูง 20 กับ 24
//   (1.75 ให้ 35 กับ 42 ซึ่งเป็นเลขคี่ · 1.80 ให้ 36 กับ 43.2 ซึ่งไม่ลงตัว)
//
// ── ทำไมเปิดครบ 5 ขนาด ───────────────────────────────────────
//   มัธยฐานของตลาดคือ 2 ขนาด และของเดิมในไฟล์ก็มี 2 ขนาด
//   แต่ผู้ใช้ตัดสิน 2026-09-04 ให้เปิดครบ xs ถึง xl เท่ากับปุ่ม
//   เหตุผลคือความสม่ำเสมอของระบบ ปุ่มเปิดครบ 5 ขนาด ถ้าสวิตช์เปิดแค่ 2
//   คนออกแบบจะต้องจำว่าชิ้นไหนมีขนาดไหนบ้าง ซึ่งเป็นภาระที่ไม่จำเป็น
//   สูตรรองรับอยู่แล้วตั้งแต่ต้น การเปิดเพิ่มจึงไม่ต้องแก้สูตร แค่เปิดชุดขนาด
//   base คิดที่ดัชนี xs เสมอเหมือน component อื่น
// ─────────────────────────────────────────────────────────────
import { SIZES, RADIUS_SCALE, CONTROL_HEIGHT } from './global-scale.config.mjs';

export const name = 'toggle';

// ── ขนาดที่สวิตช์เปิดใช้ (ครบทุกขั้นเท่าปุ่ม) ──────────────────
export const TOGGLE_SIZES = SIZES;

// ── semantic knobs · ชั้นภาพสวิตช์ ────────────────────────────
// base คิดที่ดัชนี xs → sm = base + 1×step · md = base + 2×step
export const TRACK_HEIGHT = { base: 16, step: 4 }; // 16 · 20 · 24 · 28 · 32 (sm กับ md คงค่าเดิมในไฟล์ออกแบบ)
export const TRACK_RATIO = 2;                      // ความกว้าง = ความสูง × 2
export const INSET = 2;                            // ระยะขอบในราง คงที่ทุกขนาด (ค่าที่ตลาดใช้มากที่สุด)
export const GAP = 8;                              // ระยะระหว่างสวิตช์กับข้อความ คงที่ทุกขนาด

// ── semantic knobs · ชั้นแถวที่กดได้ ──────────────────────────
export const ROW_HEIGHT = CONTROL_HEIGHT;  // 24 · 32 · 40 · 48 · 56 (อ้างสเกลกลาง ห้ามพิมพ์ค่าซ้ำ)
// บนอุปกรณ์สัมผัสยกแถวเป็นค่าเดียวทั้งสองขนาด ผ่านทั้ง 48dp ของ Android และ 44pt ของ Apple
// ทำแบบ Base Web ที่เพิ่มระยะขอบในเมื่อ pointer เป็น coarse
export const ROW_HEIGHT_TOUCH = 48;

// ทรงแคปซูล ใช้ค่าเต็มวงไม่ใช่ตัวเลขคงที่
// ⚠️ ของเดิมในไฟล์ออกแบบเป็น 12 ซึ่งพอดีกับ md (24 หาร 2) แต่ sm ถูกบีบลงเหลือ 10 อยู่แล้ว
//    ถ้าวันหนึ่งเปิดขนาดที่สูงกว่า 24 ค่า 12 จะเลิกเป็นแคปซูลโดยไม่มีใครรู้ จึงใช้ full แทน
export const RADIUS_FULL = RADIUS_SCALE.full;

// ── build: คืน semantic (knob) + component (resolved sizes) ───
// dim = helper จาก generate-scale (v → {$type:dimension,$value:'<v>px'})
export function build(dim) {
  const at = (s) => SIZES.indexOf(s);

  // ค่าตั้งต้นค่าเดียวของทั้งไฟล์ ที่เหลือเป็นผลลัพธ์ทั้งหมด
  const trackH = (s) => TRACK_HEIGHT.base + at(s) * TRACK_HEIGHT.step;
  const trackW = (s) => trackH(s) * TRACK_RATIO;
  const knob = (s) => trackH(s) - INSET * 2;
  const travel = (s) => trackW(s) - knob(s) - INSET * 2;
  const rowH = (s) => ROW_HEIGHT.base + at(s) * ROW_HEIGHT.step;
  const indent = (s) => trackW(s) + GAP;

  // ── ด่านตรวจ ต้องสอดคล้องกันเองทุกขนาด ─────────────────────
  // ถ้าใครแก้ค่าใดค่าหนึ่งแล้วบวกกลับไม่ได้ตามนี้ build จะไม่ผ่าน
  for (const s of TOGGLE_SIZES) {
    if (INSET * 2 + knob(s) !== trackH(s)) {
      throw new Error(`toggle: ขนาด ${s} ไม่ผ่านด่านตรวจ inset×2 + knob = track height (${INSET * 2} + ${knob(s)} ≠ ${trackH(s)})`);
    }
    if (trackW(s) !== trackH(s) * TRACK_RATIO) {
      throw new Error(`toggle: ขนาด ${s} ไม่ผ่านด่านตรวจ track width = track height × ${TRACK_RATIO}`);
    }
    if (travel(s) !== trackH(s)) {
      throw new Error(`toggle: ขนาด ${s} ระยะเลื่อนควรเท่ากับความสูงราง (${travel(s)} ≠ ${trackH(s)}) แปลว่าสัดส่วนหรือระยะขอบในหลุด`);
    }
    if (rowH(s) < trackH(s)) {
      throw new Error(`toggle: ขนาด ${s} แถวเตี้ยกว่าราง (${rowH(s)} < ${trackH(s)})`);
    }
  }

  const grow = (fn, note) =>
    Object.fromEntries(TOGGLE_SIZES.map((s) => [s, { ...dim(fn(s)), $description: note(fn(s), s) }]));

  const component = {
    track: {
      height: grow(trackH, (v, s) =>
        `ความสูงรางของสวิตช์ขนาด ${s} เท่ากับ ${v}px เป็นค่าตั้งต้นของทั้ง component เลือกอิสระ ไม่ได้ผูกกับความสูงปุ่ม`),
      width: grow(trackW, (v, s) =>
        `ความกว้างรางของสวิตช์ขนาด ${s} เท่ากับ ${v}px มาจากความสูง ${trackH(s)}px คูณ ${TRACK_RATIO}`),
    },
    inset: {
      ...dim(INSET),
      $description: `ระยะขอบในรางเท่ากับ ${INSET}px คงที่ทุกขนาดเพื่อให้สวิตช์ทุกขนาดดูเป็นตระกูลเดียวกัน เป็นค่าที่ตลาดใช้มากที่สุด`,
    },
    knob: {
      size: grow(knob, (v, s) =>
        `ปุ่มกลมของสวิตช์ขนาด ${s} เท่ากับ ${v}px เป็นผลลัพธ์จาก ความสูงราง ${trackH(s)} ลบ ระยะขอบใน ${INSET} คูณ 2 ห้ามตั้งเป็นตัวเลขอิสระ`),
    },
    travel: grow(travel, (v, s) =>
      `ระยะเลื่อนของปุ่มกลมในสวิตช์ขนาด ${s} เท่ากับ ${v}px เป็นผลลัพธ์จาก ความกว้างราง ลบ ปุ่มกลม ลบ ระยะขอบใน คูณ 2 ห้ามตั้งแยก`),
    gap: {
      ...dim(GAP),
      $description: `ระยะระหว่างสวิตช์กับข้อความเท่ากับ ${GAP}px คงที่ทุกขนาด`,
    },
    row: {
      height: grow(rowH, (v, s) =>
        `ความสูงแถวที่กดได้ของสวิตช์ขนาด ${s} เท่ากับ ${v}px อ้างสเกลความสูงตัวควบคุมกลาง ทำให้วางแถวเดียวกับปุ่มและช่องกรอกได้พอดี สวิตช์สูง ${trackH(s)}px จัดกึ่งกลาง เหลือช่องบนล่างข้างละ ${(v - trackH(s)) / 2}px`),
      'height-touch': {
        ...dim(ROW_HEIGHT_TOUCH),
        $description: `ความสูงแถวบนอุปกรณ์สัมผัสเท่ากับ ${ROW_HEIGHT_TOUCH}px ทั้งสองขนาด ผ่านทั้งเกณฑ์ 48dp ของ Android และ 44pt ของ Apple พร้อมกัน`,
      },
    },
    indent: grow(indent, (v, s) =>
      `ระยะเยื้องของคำอธิบายในสวิตช์ขนาด ${s} เท่ากับ ${v}px มาจาก ความกว้างราง ${trackW(s)} บวก ระยะห่าง ${GAP} ห้ามพิมพ์มือ`),
  };

  const semantic = {
    track: { base: dim(TRACK_HEIGHT.base), step: dim(TRACK_HEIGHT.step), ratio: { $type: 'number', $value: TRACK_RATIO } },
    inset: dim(INSET),
    gap: dim(GAP),
    // แถวอ้างสเกลกลาง ค่าที่เห็นตรงนี้จึงเท่ากับ CONTROL_HEIGHT เสมอ ไม่ได้พิมพ์ซ้ำ
    row: { base: dim(ROW_HEIGHT.base), step: dim(ROW_HEIGHT.step), touch: dim(ROW_HEIGHT_TOUCH) },
  };

  // สวิตช์เป็นแคปซูลล้วน ไม่มีทรงเหลี่ยม จึงมีแค่ค่าเต็มวง ไม่ต้องแตกราย 4 มุมและไม่ต้องแยกตามขนาด
  // (ทำแบบเดียวกับ avatar/radius/full ต่างจาก input ที่มุมโค้งผันตามขนาดจึงต้องแตกทีละมุม)
  const radius = { full: dim(RADIUS_FULL) };

  return { name, semantic, component, radius, radiusAppliesTo: ['toggle'] };
}
