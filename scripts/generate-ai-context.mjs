// Writes the generated lists in context/ that AI tools read when they pick a token or an icon.
//
//   node scripts/generate-ai-context.mjs           write the files
//   node scripts/generate-ai-context.mjs --check   exit 1 if a file is out of date (run after npm run tokens:build)
//
// Inputs (read only): tokens/tokens.json/component.json, semantics-light-mode.json, primitive.json,
// tokens/output/css/variables.css, tokens/output/css/typography.css, components/Icon/icons.ts,
// components/NationHouseIcon/icons.ts
// Outputs: context/tokens/token-list.md, context/tokens/semantic-tokens.md, context/icons/icon-names.md
// A token is listed only if its CSS variable really exists in variables.css.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const json = (p) => JSON.parse(read(p));
const check = process.argv.includes('--check');

const css = read('tokens/output/css/variables.css');
const cssVars = new Set([...css.matchAll(/(--ntg-[a-z0-9-]+)\s*:/g)].map((m) => m[1]));

function flat(obj, prefix = [], out = []) {
  for (const [key, val] of Object.entries(obj)) {
    if (key.startsWith('$') || !val || typeof val !== 'object') continue;
    if ('$value' in val) out.push({ path: [...prefix, key], value: val.$value, description: val.$description || '' });
    else flat(val, [...prefix, key], out);
  }
  return out;
}
const toVar = (path) => `--ntg-${path.join('-')}`;
// Figma descriptions use the middle dot as a separator. Tables here turn it into a comma (team rule: the dot is for list lines only)
const clean = (s) =>
  String(s).replace(/\s+/g, ' ').replace(/\s*\u00b7\s*/g, ', ').replace(/\|/g, '/').replace(/\u2014/g, ' ').trim();
const ref = (v) => (typeof v === 'string' ? clean(v) : clean(JSON.stringify(v)));

function table(tokens) {
  const rows = tokens
    .filter((t) => cssVars.has(toVar(t.path)))
    .map((t) => `| \`${toVar(t.path)}\` | ${ref(t.value)} | ${clean(t.description)} |`);
  return ['| CSS variable | Points to | Description |', '| --- | --- | --- |', ...rows].join('\n');
}

const HEADER = (title, from) => `# ${title}

Generated by \`node scripts/generate-ai-context.mjs\` from ${from}.
MUST NOT edit by hand. Run the script again after \`npm run tokens:build\` or after the icons are regenerated. Descriptions come from Figma and may be in Thai.
`;

// token-list.md: the component collection tokens a screen may use, plus presets and effects
const component = flat(json('tokens/tokens.json/component.json'));
const SCREEN_GROUPS = [
  ['Text', (p) => p[0] === 'color' && p[1] === 'text'],
  ['Brand text and on-brand', (p) => p[0] === 'color' && p[1] === 'brand'],
  ['Background', (p) => p[0] === 'color' && p[1] === 'background'],
  ['Border', (p) => p[0] === 'color' && p[1] === 'border'],
  ['Foreground', (p) => p[0] === 'color' && p[1] === 'foreground'],
  ['Status', (p) => p[0] === 'color' && p[1] === 'system'],
  ['AMS', (p) => p[0] === 'color' && p[1] === 'ams'],
  ['Effect colors', (p) => p[0] === 'color' && p[1] === 'effect'],
  ['Fixed colors', (p) => p[0] === 'color' && p[1] === 'other'],
  ['Icon colors', (p) => p[0] === 'icon'],
  ['Layout spacing', (p) => p[0] === 'size' && p[1] === 'space'],
  ['Layers (z-index)', (p) => p[0] === 'layer'],
  ['Motion', (p) => p[0] === 'motion'],
];
const SCREEN_TOP = new Set(['color', 'icon', 'size', 'layer', 'motion']);

const typographyCss = read('tokens/output/css/typography.css');
const presets = [...typographyCss.matchAll(/\.(ntg-typography-[a-z0-9-]+)\s*\{([^}]*)\}/g)].map((m) => {
  const prop = (name) => (m[2].match(new RegExp(`${name}:\\s*([^;]+);`)) || [])[1] || '';
  return `| \`.${m[1]}\` | ${clean(prop('font-family'))} | ${clean(prop('font-size'))} | ${clean(prop('font-weight'))} | ${clean(prop('line-height'))} |`;
});

const effectVars = [...css.matchAll(/(--ntg-(?:shadows|focused-ring|effect-background-blur)-[a-z0-9-]+)\s*:\s*([^;]+);(?:\s*\/\*\*\s*(.*?)\s*\*\/)?/g)];
const seenEffect = new Set();
const effectRows = effectVars
  .filter((m) => !seenEffect.has(m[1]) && seenEffect.add(m[1]))
  .map((m) => `| \`${m[1]}\` | ${clean(m[3] || '')} |`);

const owned = {};
for (const t of component) {
  if (SCREEN_TOP.has(t.path[0])) continue;
  owned[t.path[0]] = (owned[t.path[0]] || 0) + 1;
}

const primitiveGroups = {};
for (const t of flat(json('tokens/tokens.json/primitive.json'))) {
  const key = t.path.slice(0, 2).join('.');
  const name = toVar(t.path);
  primitiveGroups[key] = primitiveGroups[key] || { count: 0, examples: [] };
  primitiveGroups[key].count += 1;
  if (cssVars.has(name) && primitiveGroups[key].examples.length < 3) primitiveGroups[key].examples.push(name);
}

const tokenList = [
  HEADER('Tokens for screens', '`tokens/tokens.json/component.json`, `typography.css` and `variables.css`'),
  'Use these first. They are the component collection, the layer that Figma and code bind to.',
  'If nothing here fits the job, look in [semantic-tokens.md](semantic-tokens.md). If nothing fits there either, ask. Never use a primitive.',
  '',
  ...SCREEN_GROUPS.flatMap(([title, test]) => [`## ${title}`, '', table(component.filter((t) => test(t.path))), '']),
  '## Typography presets',
  '',
  'Use the class. Never set the font properties one by one.',
  '',
  '| Class | Family | Size | Weight | Line height |',
  '| --- | --- | --- | --- | --- |',
  ...presets,
  '',
  '## Shadows, focus rings and blur',
  '',
  '| CSS variable | Used for |',
  '| --- | --- |',
  ...effectRows,
  '',
  '## Tokens owned by one component',
  '',
  'Use these only inside that component\'s own code. Never on a screen and never on another component.',
  '',
  '| Prefix | Tokens |',
  '| --- | --- |',
  ...Object.entries(owned).map(([k, n]) => `| \`--ntg-${k}-*\` | ${n} |`),
  '',
  '## Primitives (never use)',
  '',
  'These are raw ramps and values from `primitive.json`. Components and screens MUST NOT use them.',
  'Some component and semantic tokens start with the same words (for example `--ntg-color-brand-on-brand-primary` is a component token,',
  '`--ntg-color-brand-500` is a primitive). When in doubt, a token is allowed only if it is listed above or in semantic-tokens.md.',
  'Exceptions: `--ntg-effect-background-blur-*` for backdrop-filter (listed above), and icon sizes, which you set with the `size` prop of Icon.',
  '',
  '| Group | Example names | Tokens |',
  '| --- | --- | --- |',
  ...Object.entries(primitiveGroups).map(
    ([k, g]) => `| ${k} | ${g.examples.map((n) => `\`${n}\``).join(', ')} | ${g.count} |`,
  ),
  '',
].join('\n');

// semantic-tokens.md: fallback colors
const semantic = flat(json('tokens/tokens.json/semantics-light-mode.json')).filter((t) => t.path[0] === 'color');
const semanticGroups = [...new Set(semantic.map((t) => t.path[1]))];
const semanticList = [
  HEADER('Semantic color tokens (fallback)', '`tokens/tokens.json/semantics-light-mode.json`'),
  'Open this only when [token-list.md](token-list.md) has no token for the job. In Figma, bind from the component collection only.',
  'Each token has a dark value with the same name in `semantics-dark-mode.json`.',
  '',
  ...semanticGroups.flatMap((g) => {
    const names = semantic.filter((t) => t.path[1] === g && cssVars.has(toVar(t.path))).map((t) => `\`${toVar(t.path)}\``);
    return [`## ${g} (${names.length})`, '', names.join(', '), ''];
  }),
].join('\n');

// icon-names.md
const iconsTs = read('components/Icon/icons.ts');
const catBlock = (iconsTs.match(/export const iconCategories[^{]*\{([\s\S]*?)\n\};/) || [])[1] || '';
const categories = [...catBlock.matchAll(/'([^']+)':\s*\[([^\]]*)\]/g)].map((m) => [
  m[1],
  [...m[2].matchAll(/'([a-z0-9-]+)'/g)].map((x) => x[1]),
]);
const houseTs = read('components/NationHouseIcon/icons.ts');
const houseUnion = (houseTs.match(/export type NationHouseIconName =([\s\S]*?);/) || [])[1] || '';
const houseNames = [...houseUnion.matchAll(/'([a-z0-9-]+)'/g)].map((m) => m[1]);
const iconNames = [
  HEADER('Icon names', '`components/Icon/icons.ts` and `components/NationHouseIcon/icons.ts`'),
  `## Nation UI Icons (${categories.reduce((n, [, list]) => n + list.length, 0)})`,
  '',
  "`<Icon name=\"...\" />` from `components/Icon`. The interface icon set. Choose by meaning; the name is the meaning.",
  '',
  '| Category | Names |',
  '| --- | --- |',
  ...categories.map(([cat, list]) => `| ${cat} | ${list.map((n) => `\`${n}\``).join(', ')} |`),
  '',
  `## Nation House Icons (${houseNames.length})`,
  '',
  '`<NationHouseIcon name="..." />` from `components/NationHouseIcon`. The Nation House brand set on a 40dp grid.',
  '',
  houseNames.map((n) => `\`${n}\``).join(', '),
  '',
].join('\n');

const outputs = [
  ['context/tokens/token-list.md', tokenList],
  ['context/tokens/semantic-tokens.md', semanticList],
  ['context/icons/icon-names.md', iconNames],
];

let stale = 0;
for (const [path, content] of outputs) {
  const full = join(ROOT, path);
  const current = existsSync(full) ? readFileSync(full, 'utf8') : '';
  if (check) {
    if (current !== content) {
      console.error(`Out of date: ${path}`);
      stale += 1;
    }
  } else if (current !== content) {
    writeFileSync(full, content);
    console.log(`Wrote ${path}`);
  } else {
    console.log(`Up to date: ${path}`);
  }
}
if (check && stale) {
  console.error('Run: node scripts/generate-ai-context.mjs');
  process.exit(1);
}
if (check) console.log('Generated context files are up to date.');
